            assemblyName: "Shop.Domain");

        Assert.True(run.Sources.ContainsKey("LiteSpecRoles.g.cs"), "The roles source is missing.");
        Assert.True(run.Sources.ContainsKey("LiteSpecPermissions.g.cs"), "The permissions source is missing.");
        Assert.Empty(run.ReportedDiagnostics);
        Assert.True(run.CompileErrors.Count == 0, "The generated code does not compile:\n" + string.Join("\n", run.CompileErrors));
    }

    /// <summary>An unknown layer generates no roles.</summary>
    /// <proves>litespec/backend/dotnet/stack#generate-the-registry-permissions-and-roles-from-the-records</proves>
    [Fact(DisplayName = "An unknown layer generates no roles")]
    public void UnknownLayerGeneratesNoRoles()
    {
        var run = GeneratorVerify.Run(
            RoleSources(),
            RecordPages.Files(
                "xml",
                ("employee.md", RecordPages.RolePage("role/employee", "self", ["permission/list-expenses"])),
                ("permissions.md", RecordPages.PermissionFactsPage(
                    RecordPages.PermissionEntry("permission/list-expenses", "self")))),
            assemblyName: "Shop.Core");

        Assert.False(run.Sources.ContainsKey("LiteSpecRoles.g.cs"), "The roles source must not be generated.");
        Assert.True(run.CompileErrors.Count == 0, "The generated code does not compile:\n" + string.Join("\n", run.CompileErrors));
    }

    private static IReadOnlyList<(string Path, string Source)> RoleSources() =>
        RecordPages.Sources("namespace Shop.Spending; internal sealed class Placeholder;");

    private static IReadOnlyList<(string Path, string Text)> ClaimwickFiles() =>
        RecordPages.FilesWithVocabulary(
            "{\"verbs\": [\"submit\", \"reimburse\", \"erase\"]}",
            ("employee.md", RecordPages.RolePage("role/employee", "self", ["permission/submit-expense", "permission/list-expenses"])),
            ("approver.md", RecordPages.RolePage("role/approver", "team", ["permission/approve-expense", "permission/list-expenses", "permission/manage-policy"])),
            ("finance.md", RecordPages.RolePage("role/finance", "platform", ["permission/reimburse-expense", "permission/list-expenses", "permission/export-expenses", "permission/erase-personal-data"])),
            ("permissions.md", RecordPages.PermissionFactsPage(
                RecordPages.PermissionEntry("permission/submit-expense", "self"),
                RecordPages.PermissionEntry("permission/list-expenses", "self"),
                RecordPages.PermissionEntry("permission/approve-expense", "team"),
                RecordPages.PermissionEntry("permission/manage-policy", "platform"),
                RecordPages.PermissionEntry("permission/reimburse-expense", "platform"),
                RecordPages.PermissionEntry("permission/export-expenses", "platform"),
                RecordPages.PermissionEntry("permission/erase-personal-data", "platform"))));

    private static object? Property(object entry, string name)
    {
        var property = entry.GetType().GetProperty(name, BindingFlags.Public | BindingFlags.Instance);
        Assert.NotNull(property);

        return property.GetValue(entry);
    }
}
