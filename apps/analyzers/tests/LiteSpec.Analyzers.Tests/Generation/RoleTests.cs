    /// <summary>Roles list each role with its scope and allows in record order.</summary>
    /// <proves>litespec/backend/dotnet/stack#generate-the-registry-permissions-and-roles-from-the-records</proves>
    [Fact(DisplayName = "Roles list each role with its scope and allows in record order")]
    public void RolesListScopeAndAllowsInRecordOrder()
    {
        var run = GeneratorVerify.Run(RoleSources(), ClaimwickFiles(), assemblyName: "Shop.Application");

        Assert.True(run.Sources.TryGetValue("LiteSpecRoles.g.cs", out var roles), "The roles source is missing.");
        Assert.Contains("// <auto-generated/>", roles, StringComparison.Ordinal);
        Assert.Contains("namespace LiteSpec", roles, StringComparison.Ordinal);
        Assert.Contains("internal static class LiteSpecRoles", roles, StringComparison.Ordinal);
        Assert.Contains("public const string Approver = \"role/approver\";", roles, StringComparison.Ordinal);
        Assert.Contains("public const string Employee = \"role/employee\";", roles, StringComparison.Ordinal);
        Assert.Contains("public const string Finance = \"role/finance\";", roles, StringComparison.Ordinal);
        Assert.Contains("internal sealed record LiteSpecRole(string Id, string Scope, System.Collections.Generic.IReadOnlyList<string> Allows);", roles, StringComparison.Ordinal);

        var approver = "new LiteSpecRole(\"role/approver\", \"team\", new string[] { \"permission/approve-expense\", \"permission/list-expenses\", \"permission/manage-policy\" })";
        var employee = "new LiteSpecRole(\"role/employee\", \"self\", new string[] { \"permission/submit-expense\", \"permission/list-expenses\" })";
        var finance = "new LiteSpecRole(\"role/finance\", \"platform\", new string[] { \"permission/reimburse-expense\", \"permission/list-expenses\", \"permission/export-expenses\", \"permission/erase-personal-data\" })";
        Assert.Contains(approver, roles, StringComparison.Ordinal);
        Assert.Contains(employee, roles, StringComparison.Ordinal);
        Assert.Contains(finance, roles, StringComparison.Ordinal);
        Assert.True(
            roles.IndexOf(approver, StringComparison.Ordinal) < roles.IndexOf(employee, StringComparison.Ordinal)
            && roles.IndexOf(employee, StringComparison.Ordinal) < roles.IndexOf(finance, StringComparison.Ordinal),
            "All is not sorted by constant name.");
        Assert.Empty(run.ReportedDiagnostics);
        Assert.True(run.CompileErrors.Count == 0, "The generated code does not compile:\n" + string.Join("\n", run.CompileErrors));
    }

    /// <summary>Of returns the entry for a known id and throws for an unknown id.</summary>
    /// <proves>litespec/backend/dotnet/stack#generate-the-registry-permissions-and-roles-from-the-records</proves>
    [Fact(DisplayName = "Of returns the entry for a known id and throws for an unknown id")]
    public void OfReturnsKnownAndThrowsForUnknown()
    {
        var sources = RoleSources();
        var run = GeneratorVerify.Run(sources, ClaimwickFiles(), assemblyName: "Shop.Application");
        Assert.True(run.Sources.ContainsKey("LiteSpecRoles.g.cs"), "The roles source is missing.");
        Assert.Empty(run.ReportedDiagnostics);

        var compilation = GeneratorVerify.CreateCompilation(sources, "Shop.Application");
        var trees = new List<SyntaxTree>();

        foreach (var generated in run.Sources)
        {
            trees.Add(CSharpSyntaxTree.ParseText(
                SourceText.From(generated.Value, Encoding.UTF8),
                new CSharpParseOptions(LanguageVersion.Latest),
                generated.Key,
                cancellationToken: TestContext.Current.CancellationToken));
        }

        using var stream = new MemoryStream();
        var emitted = compilation.AddSyntaxTrees(trees).Emit(stream, cancellationToken: TestContext.Current.CancellationToken);
        Assert.True(emitted.Success, "The generated code does not emit:\n" + string.Join("\n", emitted.Diagnostics));

        var roles = Assembly.Load(stream.ToArray()).GetType("LiteSpec.LiteSpecRoles");
        Assert.NotNull(roles);
        var of = roles.GetMethod("Of", BindingFlags.Public | BindingFlags.Static);
        Assert.NotNull(of);

        var entry = of.Invoke(null, ["role/finance"]);
        Assert.NotNull(entry);
        Assert.Equal("role/finance", Property(entry, "Id"));
        Assert.Equal("platform", Property(entry, "Scope"));
        Assert.Equal(
            new[] { "permission/reimburse-expense", "permission/list-expenses", "permission/export-expenses", "permission/erase-personal-data" },
            ((System.Collections.IEnumerable)Property(entry, "Allows")!).Cast<string>().ToArray());

        var all = roles.GetProperty("All", BindingFlags.Public | BindingFlags.Static);
        Assert.NotNull(all);
        var entries = ((System.Collections.IEnumerable)all.GetValue(null)!).Cast<object>().ToArray();
        Assert.Equal(3, entries.Length);
        Assert.Equal("role/approver", Property(entries[0], "Id"));
        Assert.Equal("role/employee", Property(entries[1], "Id"));
        Assert.Equal("role/finance", Property(entries[2], "Id"));

        var thrown = Assert.Throws<TargetInvocationException>(() => of.Invoke(null, ["role/unknown"]));
        var argument = Assert.IsType<ArgumentException>(thrown.InnerException);
        Assert.Equal("id", argument.ParamName);
    }

    /// <summary>A role without scope and allows reads empty and empty.</summary>
    /// <proves>litespec/backend/dotnet/stack#generate-the-registry-permissions-and-roles-from-the-records</proves>
    [Fact(DisplayName = "A role without scope and allows reads empty and empty")]
    public void RoleWithoutScopeAndAllowsReadsDefaults()
    {
