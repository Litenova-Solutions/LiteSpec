        Assert.Contains("public const string Onlooker = \"role/onlooker\";", roles, StringComparison.Ordinal);
        Assert.Contains("new LiteSpecRole(\"role/onlooker\", \"\", new string[] { })", roles, StringComparison.Ordinal);
        Assert.Empty(run.ReportedDiagnostics);
        Assert.True(run.CompileErrors.Count == 0, "The generated code does not compile:\n" + string.Join("\n", run.CompileErrors));
