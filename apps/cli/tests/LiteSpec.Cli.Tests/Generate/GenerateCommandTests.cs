    /// <summary>Generate --check exits 1 listing the drifted file, and a regenerate clears it.</summary>
    /// <proves>litespec/core/model#generate-record-determined-code-from-the-records</proves>
    [Fact]
    public void GenerateCheckReportsDriftAndRegenerateClearsIt()
    {
        using var temp = ModelFixture.Prepare("small");
        AppendGenerate(temp.Path, """
            generate:
            - kind: refusal-codes
              stack: dotnet
              path: apps/api/src/Modules/Library.{Module}
              namespace: Library.{Module}
            """);
        Assert.Equal(0, TestCli.Run("generate", "--root", temp.Path).Status);

        var file = Path.Combine(temp.Path, "apps", "api", "src", "Modules", "Library.Lending", "LendingRefusalCodes.generated.cs");
        File.Delete(file);

        var drifted = TestCli.Run("generate", "--root", temp.Path, "--check");
        Assert.Equal(1, drifted.Status);
        Assert.Contains("LendingRefusalCodes.generated.cs", drifted.Stdout);
        Assert.Contains("1 files would change.", drifted.Stdout);
        Assert.False(File.Exists(file));

        Assert.Equal(0, TestCli.Run("generate", "--root", temp.Path).Status);
        Assert.True(File.Exists(file));
        Assert.Equal(0, TestCli.Run("generate", "--root", temp.Path, "--check").Status);
    }

    /// <summary>Generate writes nothing and names each invalid file when a record file does not parse.</summary>
    /// <proves>litespec/core/model#generate-record-determined-code-from-the-records</proves>
    [Fact]
    public void GenerateRefusesWhenARecordFileDoesNotParse()
    {
        using var temp = ModelFixture.Prepare("small");
        AppendGenerate(temp.Path, """
            generate:
            - kind: refusal-codes
              stack: dotnet
              path: apps/api/src/Modules/Library.{Module}
              namespace: Library.{Module}
            """);
        File.WriteAllText(
            Path.Combine(temp.Path, ".litespec", "behavior", "modules", "lending", "broken.yaml"),
            "type: rule\nid: rule/lending.broken\nmeaning: The statuses, each with the day it applies from: registered or exempt\n");

        var result = TestCli.Run("generate", "--root", temp.Path);

        Assert.Equal(2, result.Status);
        Assert.Contains("broken.yaml", result.Output, StringComparison.Ordinal);
        Assert.False(File.Exists(Path.Combine(temp.Path, "apps", "api", "src", "Modules", "Library.Lending", "LendingRefusalCodes.generated.cs")));
    }

    /// <summary>Generate writes one TypeScript file per TypeScript target with the codes and their types.</summary>
    /// <proves>litespec/core/model#generate-record-determined-code-from-the-records</proves>
    [Fact]
    public void GenerateWritesTypeScriptFiles()
    {
        using var temp = ModelFixture.Prepare("small");
        AppendGenerate(temp.Path, """
            generate:
            - kind: refusal-codes
              stack: svelte
              path: apps/web/src/generated
            - kind: permissions
              stack: svelte
              path: apps/web/src/generated
            """);

        var result = TestCli.Run("generate", "--root", temp.Path);

        Assert.Equal(0, result.Status);
        var refusals = Path.Combine(temp.Path, "apps", "web", "src", "generated", "refusal-codes.ts");
        var permissions = Path.Combine(temp.Path, "apps", "web", "src", "generated", "permissions.ts");
        Assert.True(File.Exists(refusals), "refusal codes file");
        Assert.True(File.Exists(permissions), "permissions file");

        var refusalText = File.ReadAllText(refusals);
        Assert.Contains("LendingCopyNotAvailable: \"lending.copy-not-available\",", refusalText);
        Assert.Contains("export type RefusalCode = (typeof refusalCodes)[keyof typeof refusalCodes];", refusalText);
        Assert.Contains("export const refusalSentences", refusalText);

        var permissionText = File.ReadAllText(permissions);
        Assert.Contains("LendingBorrowCopy: \"permission/borrow-copy\",", permissionText);
        Assert.Contains("export type PermissionId = (typeof permissions)[keyof typeof permissions];", permissionText);
    }

