using LiteSpec.Cli.Tests.Model;
using LiteSpec.Cli.Tests.Support;

namespace LiteSpec.Cli.Tests.Generate;

/// <summary>Proves <c>litespec generate</c> writes the code the records determine.</summary>
public sealed class GenerateCommandTests
{
    /// <summary>Generate writes each configured .NET file with the generated header and the record values.</summary>
    /// <proves>litespec/core/model#generate-record-determined-code-from-the-records</proves>
    [Fact]
    public void GenerateWritesConfiguredDotnetFiles()
    {
        using var temp = ModelFixture.Prepare("small");
        AppendGenerate(temp.Path, """
            generate:
            - kind: refusal-codes
              stack: dotnet
              path: apps/api/src/Modules/Library.{Module}
              namespace: Library.{Module}
            - kind: permissions
              stack: dotnet
              path: apps/api/src/Modules/Library.{Module}
              namespace: Library.{Module}
            """);

        var result = TestCli.Run("generate", "--root", temp.Path);

        Assert.Equal(0, result.Status);
        var refusals = Path.Combine(temp.Path, "apps", "api", "src", "Modules", "Library.Lending", "LendingRefusalCodes.generated.cs");
        var permissions = Path.Combine(temp.Path, "apps", "api", "src", "Modules", "Library.Lending", "LendingPermissions.generated.cs");
        Assert.True(File.Exists(refusals), "refusal codes file");
        Assert.True(File.Exists(permissions), "permissions file");

        var refusalText = File.ReadAllText(refusals);
        Assert.Contains("// This file is generated by litespec generate from the records. Do not edit it by hand.", refusalText);
        Assert.Contains("public static class LendingRefusalCodes", refusalText);
        Assert.Contains("public const string CopyNotAvailable = \"lending.copy-not-available\";", refusalText);
        Assert.Contains("The copy is on loan or on hold for another reader.", refusalText);

        var permissionText = File.ReadAllText(permissions);
        Assert.Contains("public static class LendingPermissions", permissionText);
        Assert.Contains("public const string BorrowCopy = \"permission/borrow-copy\";", permissionText);
        Assert.Contains("LendingRefusalCodes.generated.cs", result.Stdout);
    }

    /// <summary>Generate writes nothing for a module with no entries, and exits 0 with no files.</summary>
    /// <proves>litespec/core/model#generate-record-determined-code-from-the-records</proves>
