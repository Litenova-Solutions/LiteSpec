    /// <summary>Generate writes one closed set file per home with a nested class per set.</summary>
    /// <proves>litespec/core/model#generate-record-determined-code-from-the-records</proves>
    [Fact]
    public void GenerateWritesClosedSets()
    {
        using var temp = ModelFixture.Prepare("small");
        var folder = Path.Combine(temp.Path, ".litespec", "behavior", "modules", "lending", "reference-data", "loan-kind");
        Directory.CreateDirectory(folder);
        File.WriteAllText(
            Path.Combine(folder, "loan-kind.yaml"),
            """
            type: reference-data
            id: reference-data/lending.loan-kind
            title: Loan Kind
            summary: The kinds of loan the library lends.
            choices:
            - standard
            - reference-only
            rows:
            - value: standard
              key: standard-2026
              effectiveFrom: 2026-01-01
              source: decision/0001-loan-period
            """);
        AppendGenerate(temp.Path, """
            generate:
            - kind: closed-sets
              stack: dotnet
              path: apps/api/src/Modules/Library.{Module}
              namespace: Library.{Module}
            """);

        var result = TestCli.Run("generate", "--root", temp.Path);

        Assert.Equal(0, result.Status);
        var file = Path.Combine(temp.Path, "apps", "api", "src", "Modules", "Library.Lending", "LendingClosedSets.generated.cs");
        Assert.True(File.Exists(file), "closed sets file");

        var text = File.ReadAllText(file);
        Assert.Contains("public static class LendingClosedSets", text);
        Assert.Contains("public static class LoanKind", text);
        Assert.Contains("public const string Standard = \"standard\";", text);
        Assert.Contains("public const string ReferenceOnly = \"reference-only\";", text);
    }

    /// <summary>Generate writes nothing and exits 1 naming each invalid target.</summary>
    /// <proves>litespec/core/model#generate-record-determined-code-from-the-records</proves>
    [Fact]
    public void GenerateFailsOnAnInvalidTarget()
    {
        using var temp = ModelFixture.Prepare("small");
        AppendGenerate(temp.Path, """
            generate:
            - kind: event-decisions
              stack: svelte
              path: apps/web/src/generated
            """);

        var result = TestCli.Run("generate", "--root", temp.Path);

        Assert.Equal(1, result.Status);
        Assert.Contains("event-decisions", result.Stderr, StringComparison.Ordinal);
        Assert.False(Directory.Exists(Path.Combine(temp.Path, "apps", "web", "src", "generated")));
    }

    /// <summary>Generate --help prints the usage text, and an unknown option is a usage error.</summary>
    /// <proves>litespec/core/model#generate-record-determined-code-from-the-records</proves>
    [Fact]
    public void GenerateHelpAndUsageErrors()
    {
        using var temp = ModelFixture.Prepare("small");

        var help = TestCli.Run("generate", "--help");
        Assert.Equal(0, help.Status);
        Assert.Contains("litespec generate", help.Stdout, StringComparison.Ordinal);

        var unknown = TestCli.Run("generate", "--root", temp.Path, "--bogus");
        Assert.Equal(2, unknown.Status);
    }

    /// <summary>Appends a generate block to the fixture project file.</summary>
    /// <param name="root">The prepared fixture folder.</param>
    /// <param name="yaml">The generate block YAML.</param>
    static void AppendGenerate(string root, string yaml) =>
        File.AppendAllText(Path.Combine(root, ".litespec", "project.yaml"), "\n" + yaml + "\n");
}
