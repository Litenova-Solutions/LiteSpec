using LiteSpec.Tests.Model.Frontend;
using LiteSpec.Tests.Support;

namespace LiteSpec.Tests.Model;

/// <summary>Proves <c>litespec model render</c> writes every generated output.</summary>
public sealed class RenderTests
{
    /// <summary>Render writes the records file into each web frontend frame with the render header.</summary>
    /// <proves>litespec/frontend/web/structure#generate-the-records-file-into-the-frame</proves>
    [Fact]
    public void Render_Writes_The_Records_File_Into_Each_Frame()
    {
        using var temp = FrontendMarksFixture.Prepare("clean");
        var result = Cli.Run("model", "render", "--root", temp.Path);
        Assert.Equal(0, result.Status);

        foreach (var relative in new[]
                 {
                     Path.Combine("apps", "web", "src", "lib", "app", "litespec-records.ts"),
                     Path.Combine("apps", "console", "src", "app", "litespec-records.ts"),
                 })
        {
            var file = Path.Combine(temp.Path, relative);
            Assert.True(File.Exists(file), relative);
            Assert.Contains(
                "// This file is generated by litespec model render.",
                File.ReadAllText(file));
        }

        Assert.Contains("litespec-records.ts", result.Stdout);
    }

    /// <summary>Render fills the known fenced regions, leaves unknown fences alone, and touches no text outside the fences.</summary>
    /// <proves>litespec/core/model#render-generated-regions-from-the-model</proves>
    [Fact]
    public void Render_Fills_The_Known_Regions_And_Leaves_The_Rest_Untouched()
    {
        using var temp = FrontendMarksFixture.Prepare("clean");

        var runbooks = Path.Combine(temp.Path, ".litespec", "runbooks");
        Directory.CreateDirectory(runbooks);
        File.WriteAllText(
            Path.Combine(runbooks, "clear-cache.yaml"),
            "type: runbook\nid: runbook/clear-cache\ntitle: Clear Cache\ntrigger: The cache fills.\n");

        var page = Path.Combine(
            temp.Path, ".litespec", "behavior", "modules", "lending", "loans", "borrow-copy.md");
        File.WriteAllText(
            page,
            """
            # Borrow copy

            A reader borrows an available copy.

            <!-- generated:runbook-index -->
            stale
            <!-- /generated:runbook-index -->

            <!-- generated:census -->
            kept
            <!-- /generated:census -->
            """);

        var result = Cli.Run("model", "render", "--root", temp.Path);
        Assert.Equal(0, result.Status);

        var rendered = File.ReadAllText(page);
        Assert.Contains("- [Clear Cache](", rendered);
        Assert.Contains("clear-cache.yaml): The cache fills.", rendered);
        Assert.DoesNotContain("stale", rendered);
        Assert.Contains("<!-- generated:census -->\nkept\n<!-- /generated:census -->", rendered);
        Assert.Contains("A reader borrows an available copy.", rendered);
        Assert.Contains("borrow-copy.md", result.Stdout);
    }
}
