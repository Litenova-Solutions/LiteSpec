using LiteSpec.Cli.Tests.Model.Frontend;
using LiteSpec.Cli.Tests.Support;

namespace LiteSpec.Cli.Tests.Model;

/// <summary>Proves <c>litespec model render</c> writes every generated output.</summary>
public sealed class RenderTests
{
    /// <summary>Render writes the records file into the Svelte frame with the render header.</summary>
    /// <proves>litespec/packs/svelte/structure#generate-the-records-file-into-the-frame</proves>
    [Fact]
    public void RenderWritesTheRecordsFileIntoTheSvelteFrame()
    {
        using var temp = FrontendMarksFixture.Prepare("clean");
        var result = TestCli.Run("model", "render", "--root", temp.Path);
        Assert.Equal(0, result.Status);

        var relative = Path.Combine("apps", "web", "src", "lib", "app", "litespec-records.ts");
        var file = Path.Combine(temp.Path, relative);
        Assert.True(File.Exists(file), relative);
        Assert.Contains(
            "// This file is generated by litespec model render.",
            File.ReadAllText(file));

        // Only Svelte frontends take a records file, so the console frontend takes none.
        Assert.False(File.Exists(Path.Combine(temp.Path, "apps", "console", "src", "lib", "app", "litespec-records.ts")));

        Assert.Contains("litespec-records.ts", result.Stdout);
    }

    /// <summary>Render fills the known fenced regions, leaves unknown fences alone, and touches no text outside the fences.</summary>
    /// <proves>litespec/core/model#render-generated-regions-from-the-model</proves>
    [Fact]
    public void RenderFillsTheKnownRegionsAndLeavesTheRestUntouched()
    {
        using var temp = FrontendMarksFixture.Prepare("clean");

        var runbooks = Path.Combine(temp.Path, ".litespec", "runbooks");
        Directory.CreateDirectory(runbooks);
        File.WriteAllText(
            Path.Combine(runbooks, "clear-cache.yaml"),
            "type: runbook\nid: runbook/clear-cache\ntitle: Clear Cache\ntrigger: The cache fills.\n");

        var page = Path.Combine(
            temp.Path, ".litespec", "behavior", "modules", "lending", "aggregates", "loans", "borrow-copy.md");
        File.WriteAllText(
            page,
            """
            # Borrow copy

            A reader borrows an available copy.

            <!-- generated:runbook-index -->
            stale
            <!-- /generated:runbook-index -->

            <!-- generated:census -->
            kept
            <!-- /generated:census -->
            """);

        var result = TestCli.Run("model", "render", "--root", temp.Path);
        Assert.Equal(0, result.Status);

        var rendered = File.ReadAllText(page);
        Assert.Contains("- [Clear Cache](", rendered);
        Assert.Contains("clear-cache.yaml): The cache fills.", rendered);
        Assert.DoesNotContain("stale", rendered);
        Assert.Contains("<!-- generated:census -->\nkept\n<!-- /generated:census -->", rendered);
        Assert.Contains("A reader borrows an available copy.", rendered);
        Assert.Contains("borrow-copy.md", result.Stdout);
    }

    /// <summary>Render writes nothing and names each invalid file when a record file does not parse.</summary>
    /// <proves>litespec/packs/svelte/structure#generate-the-records-file-into-the-frame</proves>
    [Fact]
    public void RenderRefusesWhenARecordFileDoesNotParse()
    {
        using var temp = FrontendMarksFixture.Prepare("clean");
        File.WriteAllText(
            Path.Combine(temp.Path, ".litespec", "behavior", "modules", "lending", "broken.yaml"),
            "type: rule\nid: rule/lending.broken\nmeaning: The statuses, each with the day it applies from: registered or exempt\n");

        var result = TestCli.Run("model", "render", "--root", temp.Path);

        Assert.Equal(2, result.Status);
        Assert.Contains("broken.yaml", result.Output, StringComparison.Ordinal);
        Assert.False(File.Exists(Path.Combine(temp.Path, "apps", "web", "src", "lib", "app", "litespec-records.ts")));
    }

    /// <summary>Render still writes when a record file parses but holds no record: refusal covers parse failures, and semantic errors block the check instead.</summary>
    /// <proves>litespec/packs/svelte/structure#generate-the-records-file-into-the-frame</proves>
    [Fact]
    public void RenderWritesWhenARecordFileParsesButHoldsNoRecord()
    {
        using var temp = FrontendMarksFixture.Prepare("clean");
        File.WriteAllText(
            Path.Combine(temp.Path, ".litespec", "behavior", "modules", "lending", "untyped.yaml"),
            "type: not-a-record-type\nid: untyped\ntitle: Untyped\n");

        var result = TestCli.Run("model", "render", "--root", temp.Path);

        Assert.Equal(0, result.Status);
        Assert.True(File.Exists(Path.Combine(temp.Path, "apps", "web", "src", "lib", "app", "litespec-records.ts")));
    }
}
