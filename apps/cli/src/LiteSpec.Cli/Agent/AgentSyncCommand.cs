/// <summary>
///     The <c>litespec agent sync</c> command: writes the thin root agent context and the
///     path-scoped rule files from the project's stacks and selected extensions only.
///     The root <c>AGENTS.md</c> stays under 100 lines and keeps every line outside its
///     marked region. Each stack area gets one rule file for Claude, one for Cursor and
///     one for GitHub, holding only the unchecked judgment provisions of that area as one
///     line each with its identifier. Two shared rule files cover record writing and
///     frontend routes, and the Claude settings gain the hook entries that run them.
/// </summary>
/// <follows>litespec/core/agent#load-applicable-provisions-before-editing</follows>
static partial class AgentSyncCommand
{
    /// <summary>The usage text for the agent sync command, printed on help and on usage errors.</summary>
    public const string Usage = """
        Usage: litespec agent sync [--root <consumer>] [--check]

        Writes the agent files from the project's stacks and selected extensions only: the thin
        root AGENTS.md under 100 lines, the path-scoped rule files .claude/rules/<area>.md,
        .cursor/rules/<area>.mdc and .github/instructions/<area>.instructions.md with one line
        per unchecked judgment provision of each selected stack's area, the shared
        .claude/rules/spec-writing.md and .claude/rules/ui-routes.md files, and the hook block
        in .claude/settings.json. With --check it writes nothing and exits 1 when any file would change.

          --root      The consumer repository to read. Defaults to the working directory.
          --check     Write nothing; list each file that would change and exit 1 when any would.
          --help      Print this text and exit.

        Exit codes: 0 the files are written, or --check found every file current, 1 a file would change
        with --check or a file cannot be read or written, 2 the options are invalid or the project file or
        the carried release cannot be read.
        """;

    /// <summary>The region name inside its fences in the root agent context.</summary>
    internal const string RegionName = "agent-sync";

    /// <summary>The marker every generated file carries on its first lines.</summary>
    internal const string Marker = "Generated by litespec agent sync.";

    /// <summary>Runs the agent sync command.</summary>
    /// <param name="args">The command arguments, the subcommand first.</param>
    /// <returns>The exit code: 0 written or current, 1 drift with --check or an unreadable file, 2 a usage error or an unreadable consumer or release.</returns>
    public static int Run(string[] args)
    {
        var rest = args;

        if (rest.Length > 0 && !rest[0].StartsWith('-'))
        {
            if (rest[0] is "--help" or "-h" or "help")
            {
                CliHost.Out.WriteLine(Usage);
                return 0;
            }

            if (rest[0] != "sync")
            {
                return CommandFailure.UsageError($"Unknown agent command '{rest[0]}'. Use sync.", Usage, json: false);
            }

            rest = rest[1..];
        }

        var parsed = CliArgs.Parse(rest, ["--check"], ["--root"], maxPositionals: 0);

        if (parsed.Help)
        {
            CliHost.Out.WriteLine(Usage);
            return 0;
        }

        if (parsed.Error is { } error)
        {
            return CommandFailure.UsageError(error, Usage, json: false);
        }

        var config = ConsumerRoot.Open(parsed.Value("--root"), json: false, out var openExit);

        if (config is null)
        {
            return openExit;
        }

        string home;

        try
        {
            home = LiteSpecHome.RequireRoot();
        }
        catch (InvalidOperationException exception)
        {
            return CommandFailure.Fail($"Cannot find the carried LiteSpec release: {exception.Message}", json: false, code: 2);
        }

        JsonObject manifest;

        try
        {
            manifest = LiteSpecHome.ReadManifest(home);
        }
        catch (Exception exception) when (exception is IOException or JsonTextException or UnauthorizedAccessException)
        {
            return CommandFailure.Fail($"The LiteSpec manifest '{LiteSpecHome.ManifestFile}' could not be read.", json: false, code: 2);
        }

        var plan = BuildPlan(config, home, manifest);
        var changed = plan.Files
            .Where(file => !File.Exists(file.AbsolutePath) || File.ReadAllText(file.AbsolutePath) != file.Content)
            .ToList();
        var check = parsed.Has("--check");

        if (!check)
        {
            foreach (var file in changed)
            {
                try
                {
                    if (Path.GetDirectoryName(file.AbsolutePath) is { Length: > 0 } folder)
                    {
                        Directory.CreateDirectory(folder);
                    }

                    File.WriteAllText(file.AbsolutePath, file.Content, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false));
                }
                catch (Exception exception) when (exception is IOException or UnauthorizedAccessException or ArgumentException or NotSupportedException)
                {
                    return CommandFailure.Fail($"Cannot write '{PathText.Relative(config.Root, file.AbsolutePath)}': {exception.Message}", json: false, code: 1);
                }
            }

            foreach (var deleted in plan.Deletions)
            {
                try
                {
                    File.Delete(deleted.AbsolutePath);
                }
                catch (Exception exception) when (exception is IOException or UnauthorizedAccessException or ArgumentException or NotSupportedException)
                {
                    return CommandFailure.Fail($"Cannot delete '{PathText.Relative(config.Root, deleted.AbsolutePath)}': {exception.Message}", json: false, code: 1);
                }
            }
        }

        foreach (var file in changed)
        {
            CliHost.Out.WriteLine(PathText.Relative(config.Root, file.AbsolutePath));
        }

        foreach (var deleted in plan.Deletions)
        {
            CliHost.Out.WriteLine(PathText.Relative(config.Root, deleted.AbsolutePath));
        }

        var total = changed.Count + plan.Deletions.Count;
        CliHost.Out.WriteLine(check ? $"{total} files would change." : $"{total} files rewritten.");
        return check && total > 0 ? 1 : 0;
    }

    /// <summary>One file the sync writes: its absolute path and its full text.</summary>
    /// <param name="AbsolutePath">The absolute file path.</param>
    /// <param name="Content">The full file text.</param>
    internal sealed record PlannedFile(string AbsolutePath, string Content);

    /// <summary>The sync plan: the files to write and the stale managed files to delete.</summary>
    /// <param name="Files">The files to write, each with its absolute path and full text.</param>
    /// <param name="Deletions">The stale managed files to delete.</param>
    internal sealed record SyncPlan(IReadOnlyList<PlannedFile> Files, IReadOnlyList<PlannedFile> Deletions);

    /// <summary>One selected stack with the folder its provisions live in.</summary>
    /// <param name="Id">The stack id the project selects.</param>
    /// <param name="Folder">The stack folder, such as <c>docs/packs/dotnet</c>.</param>
    /// <param name="Kind">The stack kind: backend or frontend.</param>
    internal sealed record Area(string Id, string Folder, string Kind);

    /// <summary>Builds the sync plan: the agent context, one rule file per area and host, the two shared rule files and the merged settings.</summary>
    /// <param name="config">The consumer configuration.</param>
    /// <param name="home">The carried LiteSpec release root.</param>
    /// <param name="manifest">The release manifest object.</param>
    /// <returns>The files to write and the stale managed files to delete.</returns>
    internal static SyncPlan BuildPlan(ConsumerConfig config, string home, JsonObject manifest)
    {
        var areas = Areas(config, manifest);
        var catalog = ProvisionCatalog.Load(home, manifest, config.Shape, config.Stacks, config.Extensions);
        var judgment = catalog.Entries
            .Where(entry => !entry.IsChecked && entry.Source == ProvisionEntry.LiteSpecSource)
            .OrderBy(entry => entry.Id, StringComparer.Ordinal)
            .ToList();
        var shipped = ShippedFolders(manifest);
        var files = new List<PlannedFile>
        {
            new PlannedFile(Path.Combine(config.Root, "AGENTS.md"), AgentsFile(config, home, manifest, areas)),
            new PlannedFile(ClaudeRulesFile(config, "spec-writing.md"), SpecWritingFile(SpecWritingEntries(judgment), BrandLines(config))),
            new PlannedFile(ClaudeRulesFile(config, "ui-routes.md"), UiRoutesFile(config, UiRouteEntries(judgment))),
            new PlannedFile(Path.Combine(config.Root, ".claude", "settings.json"), SettingsFile(config)),
        };

        foreach (var area in areas)
        {
            var entries = AreaEntries(judgment, area, shipped);
            var globs = GlobsFor(area, config);
            files.Add(new PlannedFile(ClaudeRulesFile(config, area.Id + ".md"), AreaFile(area, globs, entries, ClaudeFrontmatter(globs))));
            files.Add(new PlannedFile(Path.Combine(config.Root, ".cursor", "rules", area.Id + ".mdc"), AreaFile(area, globs, entries, CursorFrontmatter(globs))));
            files.Add(new PlannedFile(Path.Combine(config.Root, ".github", "instructions", area.Id + ".instructions.md"), AreaFile(area, globs, entries, GithubFrontmatter(globs))));
        }

        return new SyncPlan(files, StaleFiles(config, files));
    }

    /// <summary>The selected stacks that the release ships, in project order.</summary>
    /// <param name="config">The consumer configuration holding the selected stacks.</param>
    /// <param name="manifest">The release manifest object.</param>
    /// <returns>The selected shipped stacks as areas.</returns>
    internal static IReadOnlyList<Area> Areas(ConsumerConfig config, JsonObject manifest)
    {
        var shipped = StackSelection.Stacks(manifest).ToDictionary(stack => stack.Id, StringComparer.Ordinal);
        var areas = new List<Area>();

        foreach (var id in config.Stacks)
        {
            if (shipped.TryGetValue(id, out var stack) && !areas.Any(area => area.Id == id))
            {
                areas.Add(new Area(id, stack.Folder, stack.Kind));
            }
        }

        return areas;
    }

    /// <summary>Every stack folder the release ships.</summary>
    /// <param name="manifest">The release manifest object.</param>
    /// <returns>The stack folders, such as <c>docs/packs/dotnet</c>.</returns>
    static HashSet<string> ShippedFolders(JsonObject manifest) =>
        StackSelection.Stacks(manifest)
            .Select(stack => stack.Folder)
            .Where(folder => folder.Length > 0)
            .ToHashSet(StringComparer.Ordinal);

    /// <summary>The judgment provisions of one area: the stack's own pages plus the shared pages that govern every stack.</summary>
    /// <param name="judgment">Every unchecked judgment provision the selection applies.</param>
    /// <param name="area">The area.</param>
    /// <param name="shipped">Every stack folder the release ships.</param>
    /// <returns>The area provisions in identifier order.</returns>
    internal static IReadOnlyList<ProvisionEntry> AreaEntries(
        IReadOnlyList<ProvisionEntry> judgment, Area area, HashSet<string> shipped)
    {
        return judgment.Where(entry => OwnsPage(entry.Page, area.Folder, shipped)).ToList();
    }

    /// <summary>Whether the area holds the page: its own stack folder, or a shared page outside every stack folder.</summary>
    /// <param name="page">The docs-relative page path.</param>
    /// <param name="folder">The area's stack folder.</param>
    /// <param name="shipped">Every stack folder the release ships.</param>
    /// <returns>True when the area holds the page.</returns>
    internal static bool OwnsPage(string page, string folder, HashSet<string> shipped)
    {
        foreach (var other in shipped)
        {
            if (page == other + "/stack.md" || page.StartsWith(other + "/", StringComparison.Ordinal))
            {
                return string.Equals(other, folder, StringComparison.Ordinal);
            }
        }

        return true;
    }

    /// <summary>The provisions the record-writing rules file carries: every provision on the writing page.</summary>
    /// <param name="judgment">Every unchecked judgment provision the selection applies.</param>
    /// <returns>The writing page provisions in identifier order.</returns>
    internal static IReadOnlyList<ProvisionEntry> SpecWritingEntries(IReadOnlyList<ProvisionEntry> judgment) =>
        judgment.Where(entry => entry.Page == "docs/core/writing.md").ToList();

    /// <summary>The provisions the route rules file carries: the judgment provisions about routes and the pages that shape them.</summary>
    /// <param name="judgment">Every unchecked judgment provision the selection applies.</param>
    /// <returns>The route provisions in identifier order.</returns>
    internal static IReadOnlyList<ProvisionEntry> UiRouteEntries(IReadOnlyList<ProvisionEntry> judgment) =>
        judgment.Where(entry =>
            entry.AppliesTo.Contains("route", StringComparison.OrdinalIgnoreCase)
            || entry.Page.Contains("ui-ia", StringComparison.Ordinal)
            || entry.Page.Contains("ui-primitives", StringComparison.Ordinal)
            || entry.Page.Contains("screens", StringComparison.Ordinal)
            || entry.Page.Contains("golden-slice", StringComparison.Ordinal)).ToList();

    /// <summary>The path globs one area file scopes to: the source folders the project declares for the stack, or the stack's conventional folders.</summary>
    /// <param name="area">The area.</param>
    /// <param name="config">The consumer configuration.</param>
    /// <returns>The globs in stable order.</returns>
    internal static IReadOnlyList<string> GlobsFor(Area area, ConsumerConfig config)
    {
        if (area.Kind == "backend")
        {
            var roots = new List<string>();
            roots.AddRange(config.ModulesRoots);
            roots.AddRange(config.WebApiRoots);
            roots.AddRange(config.WorkerRoots);

            if (config.KernelRoot.Length > 0)
            {
                roots.Add(config.KernelRoot);
            }

            if (config.PlatformRoot.Length > 0)
            {
                roots.Add(config.PlatformRoot);
            }

            var globs = roots
                .Select(root => PathText.Relative(config.Root, root))
                .Where(relative => relative is not ("" or "."))
                .Select(relative => relative.Replace(Path.DirectorySeparatorChar, '/') + "/**/*.cs")
                .Distinct(StringComparer.Ordinal)
                .OrderBy(glob => glob, StringComparer.Ordinal)
                .ToList();

            return globs.Count > 0 ? globs : ["apps/api/**/*.cs"];
        }

        var matching = config.Frontends
            .Where(frontend => string.Equals(frontend.Platform, area.Id, StringComparison.OrdinalIgnoreCase))
            .ToList();
        var folders = matching.Count > 0 ? matching : config.Frontends;
        var paths = folders
            .Select(frontend => PathText.Relative(config.Root, frontend.Path))
            .Where(relative => relative is not ("" or "."))
            .Select(relative => relative.Replace(Path.DirectorySeparatorChar, '/') + "/**/*")
            .Distinct(StringComparer.Ordinal)
            .OrderBy(glob => glob, StringComparer.Ordinal)
            .ToList();

        if (paths.Count > 0)
        {
            return paths;
        }

        return [FallbackFrontendGlob(area.Id)];
    }

    /// <summary>The conventional glob for a frontend stack with no declared frontend.</summary>
    /// <param name="stack">The stack id.</param>
    /// <returns>The conventional glob for the stack.</returns>
    internal static string FallbackFrontendGlob(string stack) => stack.ToLowerInvariant() switch
    {
        "svelte" or "react" => "apps/web/src/**/*",
        "blazor" => "apps/web/**/*",
        "android" => "apps/android/**/*",
        _ => $"apps/{stack.ToLowerInvariant()}/**/*",
    };

    /// <summary>The absolute Claude rule file for a rule name.</summary>
    /// <param name="config">The consumer configuration holding the root.</param>
    /// <param name="name">The rule file name.</param>
    /// <returns>The absolute rule file path.</returns>
    static string ClaudeRulesFile(ConsumerConfig config, string name) =>
        Path.Combine(config.Root, ".claude", "rules", name);

    /// <summary>One area rule file: its frontmatter, its marker, and one line per provision with its identifier.</summary>
    /// <param name="area">The area.</param>
    /// <param name="globs">The path globs the file scopes to.</param>
    /// <param name="entries">The area provisions in identifier order.</param>
    /// <param name="frontmatter">The host frontmatter holding the globs.</param>
    /// <returns>The full file text.</returns>
    internal static string AreaFile(Area area, IReadOnlyList<string> globs, IReadOnlyList<ProvisionEntry> entries, string frontmatter)
    {
        var lines = new List<string> { frontmatter, $"# {area.Id} Rules", "", MarkerLine(), "" };
        lines.Add($"Follow these provisions for files under {string.Join(", ", globs.Select(glob => "`" + glob + "`"))}.");
        lines.Add("Each line names its provision; run `litespec rules <path>` for the rationale and the example.");
        lines.Add("");

        if (entries.Count == 0)
        {
            lines.Add("No unchecked judgment provisions apply to this area.");
        }
        else
        {
            foreach (var entry in entries)
            {
                lines.Add($"- {entry.Id}: {OneLine(entry.Statement)}");
            }
        }

        return string.Join("\n", lines) + "\n";
    }

    /// <summary>The record-writing rule file: the YAML clarity rules of the writing page and the project's brand voice.</summary>
    /// <param name="entries">The writing page provisions in identifier order.</param>
    /// <param name="brand">The brand voice lines from the product record.</param>
    /// <returns>The full file text.</returns>
    internal static string SpecWritingFile(IReadOnlyList<ProvisionEntry> entries, IReadOnlyList<string> brand)
    {
        var lines = new List<string>
        {
            "---",
            "paths:",
            "  - \".litespec/**/*.yaml\"",
            "---",
            "# Record Writing Rules",
            "",
            MarkerLine(),
            "",
            "Write every record field in this project by these rules.",
            "",
        };

        foreach (var entry in entries)
        {
            lines.Add($"- {entry.Id}: {OneLine(entry.Statement)}");
        }

        lines.Add("");
        lines.Add("## Brand Voice");
        lines.Add("");

        foreach (var line in brand)
        {
            lines.Add(line);
        }

        return string.Join("\n", lines) + "\n";
    }

    /// <summary>The route rule file: the fixed route guidance and one line per route provision with its identifier.</summary>
    /// <param name="config">The consumer configuration.</param>
    /// <param name="entries">The route provisions in identifier order.</param>
    /// <returns>The full file text.</returns>
    internal static string UiRoutesFile(ConsumerConfig config, IReadOnlyList<ProvisionEntry> entries)
    {
        var globs = RouteGlobs(config);
        var lines = new List<string> { "---", "paths:" };
        lines.AddRange(globs.Select(glob => $"  - \"{glob}\""));
        lines.Add("---");
        lines.Add("# Route Rules");
        lines.Add("");
        lines.Add(MarkerLine());
        lines.Add("");
        lines.Add("Compose every route from one locked archetype, and keep one job per route.");
        lines.Add("Build pages from the locked primitives of the project's frontend stack.");
        lines.Add("");

        foreach (var entry in entries)
        {
            lines.Add($"- {entry.Id}: {OneLine(entry.Statement)}");
        }

        return string.Join("\n", lines) + "\n";
    }

    /// <summary>The route globs the route rule file scopes to: each declared frontend's routes, or the conventional route folders.</summary>
    /// <param name="config">The consumer configuration.</param>
    /// <returns>The route globs in stable order.</returns>
    internal static IReadOnlyList<string> RouteGlobs(ConsumerConfig config)
    {
        var globs = new List<string>();

        foreach (var frontend in config.Frontends)
        {
            var relative = PathText.Relative(config.Root, frontend.Path);

            if (relative is "" or ".")
            {
                continue;
            }

            var folder = relative.Replace(Path.DirectorySeparatorChar, '/');

            if (frontend.Platform == "svelte")
            {
                globs.Add(folder + "/src/routes/**");
            }
            else if (frontend.Platform == "react")
            {
                globs.Add(folder + "/src/routes/**");
            }
            else if (frontend.Platform == "android")
            {
                globs.Add(folder + "/**/Screens/**");
            }
            else
            {
                globs.Add(folder + "/**/*");
            }
        }

        if (globs.Count == 0)
        {
            globs.Add("apps/web/src/routes/**");
            globs.Add("apps/**/Screens/**");
        }

        return globs.Distinct(StringComparer.Ordinal).OrderBy(glob => glob, StringComparer.Ordinal).ToList();
    }

    /// <summary>The Claude frontmatter holding the path globs.</summary>
    /// <param name="globs">The path globs the file scopes to.</param>
    /// <returns>The frontmatter text.</returns>
    internal static string ClaudeFrontmatter(IReadOnlyList<string> globs) =>
        "---\npaths:\n" + string.Join("\n", globs.Select(glob => $"  - \"{glob}\"")) + "\n---";

    /// <summary>The Cursor frontmatter holding the path globs.</summary>
    /// <param name="globs">The path globs the file scopes to.</param>
    /// <returns>The frontmatter text.</returns>
    internal static string CursorFrontmatter(IReadOnlyList<string> globs) =>
        "---\nglobs:\n" + string.Join("\n", globs.Select(glob => $"  - \"{glob}\"")) + "\n---";

    /// <summary>The GitHub frontmatter holding the path globs.</summary>
    /// <param name="globs">The path globs the file scopes to.</param>
    /// <returns>The frontmatter text.</returns>
    internal static string GithubFrontmatter(IReadOnlyList<string> globs) =>
        "---\napplyTo: \"" + string.Join(",", globs) + "\"\n---";

    /// <summary>The marker line every generated rule file carries.</summary>
    /// <returns>The marker line.</returns>
    internal static string MarkerLine() => $"<!-- {Marker} Do not edit by hand; run litespec agent sync. -->";

    /// <summary>The thin root agent context: what the project is, the stacks, the commands to run, where the rules live and the golden slice pointers.</summary>
    /// <param name="config">The consumer configuration.</param>
    /// <param name="home">The carried LiteSpec release root.</param>
    /// <param name="manifest">The release manifest object.</param>
    /// <param name="areas">The selected stacks as areas.</param>
    /// <returns>The full file text with the marked region.</returns>
    internal static string AgentsFile(ConsumerConfig config, string home, JsonObject manifest, IReadOnlyList<Area> areas)
    {
        var release = LiteSpecHome.Version ?? "unknown";
        var stacks = AgentProtocol.FormatStacks(config.Stacks);
        var extensions = AgentProtocol.FormatExtensions(config.Extensions);
        var layers = AgentProtocol.FormatLayers(config.Layers);
        var body = new List<string>
        {
            $"This project follows LiteSpec {release}: size {config.Size}, shape {config.Shape}, stacks {stacks}, extensions {extensions}.",
            $"Layers: {layers}.",
            "",
            "Run these commands from the consumer root:",
            "- `litespec rules <path>` before editing a file, and answer each judgment provision it returns.",
            "- `litespec model check --only-paths <paths>` for the files you changed.",
            "- `litespec agent sync --check` after changing the stacks or the extensions.",
            "",
            "The path-scoped rules live in `.claude/rules/`, `.cursor/rules/` and `.github/instructions/`: open the file whose frontmatter paths cover the file you edit.",
            "Record field rules for `.litespec/**/*.yaml` live in `.claude/rules/spec-writing.md`.",
            "Route rules for the frontends live in `.claude/rules/ui-routes.md`.",
            "",
        };

        var slices = areas
            .Select(area => area.Folder + "/golden-slice.md")
            .Where(page => File.Exists(Path.Combine(home, page.Replace('/', Path.DirectorySeparatorChar))))
            .ToList();

        if (slices.Count > 0)
        {
            body.Add("Golden slices that show the intended shape:");
            body.AddRange(slices.Select(slice => $"- `{slice}`"));
            body.Add("");
        }

        body.Add("Between a record and its explanation file, the record wins.");

        var newline = "\n";
        var file = Path.Combine(config.Root, "AGENTS.md");
        var region = BuildRegion(string.Join("\n", body), newline);

        if (!File.Exists(file))
        {
            return $"# {ProductTitle(config)} Agent Notes\n\n{region}\n";
        }

        var text = File.ReadAllText(file);
        newline = text.Contains("\r\n", StringComparison.Ordinal) ? "\r\n" : "\n";
        region = BuildRegion(string.Join("\n", body), newline);

        return FindRegion(text) is not null
            ? Region().Replace(text, _ => region)
            : AgentProtocol.Insert(text, region, newline);
    }

    /// <summary>The merged Claude settings: the PostToolUse and Stop hook entries that run the hook command, merged into the existing settings.</summary>
    /// <param name="config">The consumer configuration holding the root.</param>
    /// <returns>The full settings text.</returns>
    internal static string SettingsFile(ConsumerConfig config)
    {
        var file = Path.Combine(config.Root, ".claude", "settings.json");
        JsonObject settings;

        try
        {
            settings = File.Exists(file) && JsonNode.Parse(File.ReadAllText(file)) is JsonObject parsed
                ? parsed
                : new JsonObject();
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException or JsonException)
        {
            settings = new JsonObject();
        }

        if (settings["hooks"] is not JsonObject hooks)
        {
            hooks = new JsonObject();
            settings["hooks"] = hooks;
        }

        EnsureHookEntry(hooks, "PostToolUse", "Edit|Write", "litespec hook post-edit");
        EnsureStopEntry(hooks, "litespec hook pre-stop");

        return settings.ToJsonString(new JsonSerializerOptions { WriteIndented = true }) + "\n";
    }

    /// <summary>Adds a matcher hook entry when no entry with the matcher runs the command yet. Arrays are rebuilt rather than appended to, so the trimmed build keeps every node.</summary>
    /// <param name="hooks">The hooks object of the settings.</param>
    /// <param name="name">The hook name, such as PostToolUse.</param>
    /// <param name="matcher">The matcher, such as Edit|Write.</param>
    /// <param name="command">The hook command to run.</param>
    internal static void EnsureHookEntry(JsonObject hooks, string name, string matcher, string command)
    {
        var groups = new List<JsonObject>();

        if (hooks[name] is JsonArray list)
        {
            foreach (var item in list)
            {
                if (item is JsonObject candidate)
                {
                    groups.Add((JsonObject)candidate.DeepClone());
                }
            }
        }

        var group = groups.FirstOrDefault(candidate => JsonValues.AsString(candidate["matcher"]) == matcher);

        if (group is null)
        {
            group = new JsonObject { ["matcher"] = matcher, ["hooks"] = new JsonArray() };
            groups.Add(group);
        }

        var entries = new List<JsonObject>();

        if (group["hooks"] is JsonArray existing)
        {
            foreach (var item in existing)
            {
                if (item is JsonObject candidate)
                {
                    entries.Add((JsonObject)candidate.DeepClone());
                }
            }
        }

        if (!entries.Any(entry => JsonValues.AsString(entry["command"]) == command))
        {
            entries.Add(new JsonObject { ["type"] = "command", ["command"] = command });
        }

        group["hooks"] = new JsonArray([.. entries.Select(entry => (JsonNode?)entry)]);
        hooks[name] = new JsonArray([.. groups.Select(candidate => (JsonNode?)candidate)]);
    }

    /// <summary>Adds a Stop hook entry when no entry runs the command yet. Arrays are rebuilt rather than appended to, so the trimmed build keeps every node.</summary>
    /// <param name="hooks">The hooks object of the settings.</param>
    /// <param name="command">The hook command to run.</param>
    internal static void EnsureStopEntry(JsonObject hooks, string command)
    {
        var groups = new List<JsonObject>();

        if (hooks["Stop"] is JsonArray list)
        {
            foreach (var item in list)
            {
                if (item is JsonObject candidate)
                {
                    groups.Add((JsonObject)candidate.DeepClone());
                }
            }
        }

        if (!groups.Any(group => group["hooks"] is JsonArray entries
            && entries.OfType<JsonObject>().Any(entry => JsonValues.AsString(entry["command"]) == command)))
        {
            var added = new JsonObject
            {
                ["hooks"] = new JsonArray((JsonNode)new JsonObject { ["type"] = "command", ["command"] = command }),
            };
            groups.Add(added);
        }

        hooks["Stop"] = new JsonArray([.. groups.Select(candidate => (JsonNode?)candidate)]);
    }

    /// <summary>The brand voice lines from the product record, or the universal baseline when the product declares none.</summary>
    /// <param name="config">The consumer configuration holding the root.</param>
    /// <returns>The brand voice lines.</returns>
    internal static IReadOnlyList<string> BrandLines(ConsumerConfig config)
    {
        try
        {
            var file = Path.Combine(config.Root, ".litespec", "product.yaml");

            if (File.Exists(file) && RecordText.Parse(File.ReadAllText(file), true) is JsonObject product
                && product["brand"] is JsonObject brand)
            {
                var lines = brand
                    .Where(property => JsonValues.AsString(property.Value) is { Length: > 0 })
                    .Select(property => $"- {property.Key}: {JsonValues.AsString(property.Value)}")
                    .ToList();

                if (lines.Count > 0)
                {
                    return lines;
                }
            }
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException or JsonTextException)
        {
        }

        return ["No brand voice is declared in `.litespec/product.yaml`; use the universal baseline: state what happened and the next step, list no raw refusal code, and place no blame on the reader."];
    }

    /// <summary>The project title from the product record, or the root folder name when it names none.</summary>
    /// <param name="config">The consumer configuration holding the root.</param>
    /// <returns>The project title.</returns>
    internal static string ProductTitle(ConsumerConfig config)
    {
        try
        {
            var file = Path.Combine(config.Root, ".litespec", "product.yaml");

            if (File.Exists(file) && RecordText.Parse(File.ReadAllText(file), true) is JsonObject product
                && JsonValues.AsString(product["title"]) is { Length: > 0 } title)
            {
                return title;
            }
        }
        catch (Exception exception) when (exception is IOException or UnauthorizedAccessException or JsonTextException)
        {
        }

        return new DirectoryInfo(config.Root).Name;
    }

    /// <summary>The stale managed files to delete: generated rule files for areas the project no longer selects.</summary>
    /// <param name="config">The consumer configuration holding the root.</param>
    /// <param name="files">The files the plan writes.</param>
    /// <returns>The stale managed files.</returns>
    internal static IReadOnlyList<PlannedFile> StaleFiles(ConsumerConfig config, IReadOnlyList<PlannedFile> files)
    {
        var wanted = files.Select(file => file.AbsolutePath).ToHashSet(StringComparer.OrdinalIgnoreCase);
        var stale = new List<PlannedFile>();

        foreach (var folder in new[]
        {
            Path.Combine(config.Root, ".claude", "rules"),
            Path.Combine(config.Root, ".cursor", "rules"),
            Path.Combine(config.Root, ".github", "instructions"),
        })
        {
            string[] actual;

            try
            {
                actual = Directory.Exists(folder) ? Directory.GetFiles(folder) : [];
            }
            catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
            {
                continue;
            }

            foreach (var file in actual)
            {
                if (wanted.Contains(file))
                {
                    continue;
                }

                string text;

                try
                {
                    text = File.ReadAllText(file);
                }
                catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
                {
                    continue;
                }

                if (text.Contains(Marker, StringComparison.Ordinal))
                {
                    stale.Add(new PlannedFile(file, ""));
                }
            }
        }

        stale.Sort((left, right) => string.CompareOrdinal(left.AbsolutePath, right.AbsolutePath));
        return stale;
    }

    /// <summary>Builds the full region text from a filled body: the fences with the body between them.</summary>
    /// <param name="body">The filled region body without fences.</param>
    /// <param name="newline">The line ending the region uses.</param>
    /// <returns>The region including its fences.</returns>
    internal static string BuildRegion(string body, string newline) =>
        $"<!-- generated:{RegionName} -->{newline}{body.ReplaceLineEndings(newline)}{newline}<!-- /generated:{RegionName} -->";

    /// <summary>The region match in a text, or null when the text holds no agent-sync region.</summary>
    /// <param name="text">The text to search.</param>
    /// <returns>The region match, or null.</returns>
    internal static Match? FindRegion(string text)
    {
        var match = Region().Match(text);

        return match.Success ? match : null;
    }

    /// <summary>The agent-sync region expression.</summary>
    /// <returns>The region expression.</returns>
    [GeneratedRegex("<!-- generated:agent-sync -->.*?<!-- /generated:agent-sync -->", RegexOptions.Singleline)]
    private static partial Regex Region();

    /// <summary>One statement as one line: inner newlines read as spaces.</summary>
    /// <param name="statement">The provision statement.</param>
    /// <returns>The statement with inner whitespace collapsed to spaces.</returns>
    internal static string OneLine(string statement) =>
        SingleSpace().Replace(statement, " ").Trim();

    /// <summary>A run of whitespace the one-line form collapses.</summary>
    /// <returns>The whitespace expression.</returns>
    [GeneratedRegex(@"\s+")]
    private static partial Regex SingleSpace();
