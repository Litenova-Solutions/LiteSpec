namespace LiteSpec.Cli.Generate;

/// <summary>
///     Renders the closed value sets the records declare as C#: per set a partial
///     abstract record with one sealed case per value, a stable Code, FromCode and
///     TryFromCode lookups, and All. A hand-written sibling file may add members to
///     any generated type.
/// </summary>
/// <follows>litespec/core/model#generate-record-determined-code-from-the-records</follows>
static class ClosedSetsRenderer
{
    /// <summary>One closed value set a record declares: its record, its name, its summary, and its values with their stated meanings.</summary>
    /// <param name="RecordId">The identifier of the record declaring the set.</param>
    /// <param name="Name">The set name, the name segment of the record identifier.</param>
    /// <param name="Summary">The record summary or meaning, or null when the record states neither.</param>
    /// <param name="Values">The allowed value texts.</param>
    /// <param name="Meanings">The stated meaning by value text.</param>
    public sealed record ClosedSet(
        string RecordId,
        string Name,
        string? Summary,
        IReadOnlyList<string> Values,
        IReadOnlyDictionary<string, string> Meanings);

    /// <summary>
    ///     Renders one home's closed value sets as C#: per set a public abstract partial
    ///     record with one public sealed partial case per value, named from the base name
    ///     and the value in PascalCase.
    /// </summary>
    /// <param name="home">The record home name: a module or a knowledge area.</param>
    /// <param name="sets">The home's closed value sets.</param>
    /// <param name="namespace">The C# namespace of the generated types.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(string home, IReadOnlyList<ClosedSet> sets, string @namespace)
    {
        var lines = new List<string>
        {
            GenerateNaming.HeaderLineFor(GenerateNaming.CurrentVersion()),
            "// <auto-generated/>",
            "",
            "using System;",
            "using System.Collections.Generic;",
            "using System.Diagnostics.CodeAnalysis;",
            "",
            $"namespace {@namespace};",
            "",
        };

        var ordered = sets.OrderBy(candidate => candidate.RecordId, StringComparer.Ordinal).ToList();
        var taken = new HashSet<string>(StringComparer.Ordinal);
        var bases = ordered
            .Select(set => GenerateNaming.UniqueName(GenerateNaming.ConstName(set.Name), taken))
            .ToList();
        var first = true;

        for (var index = 0; index < ordered.Count; index++)
        {
            if (!first)
            {
                lines.Add("");
            }

            first = false;
            RenderSet(lines, ordered[index], bases[index], taken);
        }

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>Renders one closed value set: its abstract base with the lookups, then one sealed case per value.</summary>
    /// <param name="lines">The file lines the set is appended to.</param>
    /// <param name="set">The closed value set.</param>
    /// <param name="baseName">The base record name, unique in the file.</param>
    /// <param name="taken">The type names already used in the file, appended in place.</param>
    static void RenderSet(List<string> lines, ClosedSet set, string baseName, HashSet<string> taken)
    {
        var spaced = set.Name.Replace('-', ' ');
        var summary = Flatten(set.Summary) is { Length: > 0 } stated
            ? stated
            : $"The {spaced} closed value set.";

        lines.Add($"/// <summary>{GenerateNaming.EscapeXml(summary)} Closed value set <c>{GenerateNaming.EscapeXml(set.RecordId)}</c>.</summary>");
        lines.Add($"public abstract partial record {baseName}");
        lines.Add("{");
        lines.Add($"    /// <summary>The stable {spaced} code.</summary>");
        lines.Add("    public abstract string Code { get; }");
        lines.Add("");
        lines.Add($"    /// <summary>Reads the {spaced} of one code.</summary>");
        lines.Add($"    /// <param name=\"code\">The stable {spaced} code.</param>");
        lines.Add($"    /// <returns>The {spaced} holding the code.</returns>");
        lines.Add($"    /// <exception cref=\"ArgumentException\">The code names no {spaced}.</exception>");
        lines.Add($"    public static {baseName} FromCode(string code) => TryFromCode(code, out var value)");
        lines.Add("        ? value");
        lines.Add($"        : throw new ArgumentException($\"Unknown {spaced} code '{{code}}'.\", nameof(code));");
        lines.Add("");
        lines.Add($"    /// <summary>Tries to read the {spaced} of one code.</summary>");
        lines.Add($"    /// <param name=\"code\">The stable {spaced} code, or an unknown label.</param>");
        lines.Add($"    /// <param name=\"value\">The {spaced} holding the code, or null when the code names none.</param>");
        lines.Add("    /// <returns>True when a case holds the code; otherwise false.</returns>");
        lines.Add($"    public static bool TryFromCode(string? code, [NotNullWhen(true)] out {baseName}? value)");
        lines.Add("    {");
        lines.Add("        value = code switch");
        lines.Add("        {");

        var cases = CaseNames(set, baseName, taken);

        foreach (var (text, name) in cases)
        {
            lines.Add($"            \"{GenerateNaming.EscapeLiteral(text)}\" => new {name}(),");
        }

        lines.Add("            _ => null,");
        lines.Add("        };");
        lines.Add("");
        lines.Add("        return value is not null;");
        lines.Add("    }");
        lines.Add("");
        lines.Add($"    /// <summary>Every known {spaced}, in code order.</summary>");

        if (cases.Count == 0)
        {
            lines.Add($"    public static IReadOnlyList<{baseName}> All {{ get; }} = Array.Empty<{baseName}>();");
        }
        else
        {
            lines.Add($"    public static IReadOnlyList<{baseName}> All {{ get; }} = new {baseName}[]");
            lines.Add("    {");

            foreach (var (_, name) in cases)
            {
                lines.Add($"        new {name}(),");
            }

            lines.Add("    };");
        }

        lines.Add("}");

        foreach (var (text, name) in cases)
        {
            lines.Add("");
            lines.AddRange(CaseDoc(set, text, spaced));
            lines.Add($"public sealed partial record {name} : {baseName}");
            lines.Add("{");
            lines.Add($"    /// <summary>The stable {spaced} code.</summary>");
            lines.Add($"    public override string Code => \"{GenerateNaming.EscapeLiteral(text)}\";");
            lines.Add("}");
        }
    }

    /// <summary>The case names of one set in code order: the base name with the PascalCase value, unique in the file.</summary>
    /// <param name="set">The closed value set.</param>
    /// <param name="baseName">The base record name.</param>
    /// <param name="taken">The type names already used in the file, appended in place.</param>
    /// <returns>The value text with its case name, ordered by value text.</returns>
    static List<(string Text, string Name)> CaseNames(ClosedSet set, string baseName, HashSet<string> taken)
    {
        var cases = new List<(string Text, string Name)>();

        foreach (var text in set.Values.OrderBy(text => text, StringComparer.Ordinal))
        {
            cases.Add((text, GenerateNaming.UniqueName(baseName + GenerateNaming.SanitizeConstName(text), taken)));
        }

        return cases;
    }

    /// <summary>The documentation lines of one case: its stated meaning, or the value text when the record states none.</summary>
    /// <param name="set">The closed value set.</param>
    /// <param name="text">The value text.</param>
    /// <param name="spaced">The set name in words.</param>
    /// <returns>The documentation lines.</returns>
    static List<string> CaseDoc(ClosedSet set, string text, string spaced) =>
        set.Meanings.TryGetValue(text, out var meaning) && Flatten(meaning) is { Length: > 0 } stated
            ? GenerateNaming.XmlDocLines(stated, "")
            : [$"/// <summary>The \"{GenerateNaming.EscapeXml(text)}\" {spaced}.</summary>"];

    /// <summary>Flattens prose onto one line, or null when the text is absent.</summary>
    /// <param name="text">The prose, or null.</param>
    /// <returns>The prose with every line break as one space, or null.</returns>
    static string? Flatten(string? text) =>
        text?.Replace("\r\n", " ", StringComparison.Ordinal).Replace('\n', ' ').Replace('\r', ' ');
}
