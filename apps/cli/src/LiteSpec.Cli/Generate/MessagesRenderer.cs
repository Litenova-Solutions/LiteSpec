using LiteSpec.Model;

namespace LiteSpec.Cli.Generate;

/// <summary>
///     Renders the command or query of one use case as C#: a partial record with the tenant key
///     first when the tenancy selection implies one, one positional property per input in written
///     order, the paging members the record implies, the idempotency key computed from the key
///     template, and the LiteBus message interface the target names. A hand-written sibling file
///     may add members to the generated type.
/// </summary>
/// <follows>litespec/core/model#generate-record-determined-code-from-the-records</follows>
static class MessagesRenderer
{
    /// <summary>The paging members a paged query carries, from its paging block.</summary>
    /// <param name="Cursor">The cursor text the record states, or null when the query pages by offset.</param>
    /// <param name="Offset">The offset text the record states, or null when the query pages by cursor.</param>
    /// <param name="DefaultLimit">The rows per page the record states.</param>
    public sealed record MessagePaging(string? Cursor, string? Offset, int DefaultLimit);

    /// <summary>The idempotency key a keyed command computes from its key template.</summary>
    /// <param name="Template">The key template the record states.</param>
    /// <param name="Expression">The key selector body: an interpolated string over the message properties, or a plain literal when the template names no property.</param>
    public sealed record MessageKey(string Template, string Expression);

    /// <summary>The tenant key a message carries first: the tenant aggregate's identifier, or a Guid when no aggregate carries the term name.</summary>
    /// <param name="Property">The tenant property name.</param>
    /// <param name="Type">The tenant key C# type.</param>
    public sealed record TenantKey(string Property, string Type);

    /// <summary>One use-case message the plan renders.</summary>
    /// <param name="UseCaseId">The use case identifier.</param>
    /// <param name="MessageType">The message type name, such as BorrowCopyCommand.</param>
    /// <param name="ResultType">The result type name the message interface carries.</param>
    /// <param name="Summary">The summary the record states, or null when the record states none.</param>
    /// <param name="Inputs">The input fields with their C# types, in written order.</param>
    /// <param name="Tenant">The tenant key, or null when the use case implies none.</param>
    /// <param name="Paging">The paging members, or null when the use case pages nothing.</param>
    /// <param name="Key">The idempotency key, or null when the command keys none.</param>
    /// <param name="Namespace">The C# namespace of the generated record.</param>
    /// <param name="MessageInterface">The LiteBus message interface as the target declares it, qualified or simple, or empty when the target names none.</param>
    /// <param name="Usings">The C# namespaces the target declares for referenced identifier and value types.</param>
    /// <param name="IsPublic">True when the message answers a public use case from the Contracts project.</param>
    public sealed record MessageData(
        string UseCaseId,
        string MessageType,
        string ResultType,
        string? Summary,
        IReadOnlyList<MessageFieldTypes.MappedField> Inputs,
        TenantKey? Tenant,
        MessagePaging? Paging,
        MessageKey? Key,
        string Namespace,
        string MessageInterface,
        IReadOnlyList<string> Usings,
        bool IsPublic);

    /// <summary>
    ///     Renders one use-case message as C#: a partial record named for the use case and its
    ///     kind, with the implied tenant key first, one positional property per input, the paging
    ///     members, and the message interface over its result. A keyed command nests its computed key.
    /// </summary>
    /// <param name="data">The use-case message the plan renders.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(MessageData data)
    {
        var lines = new List<string>
        {
            GenerateNaming.HeaderLineFor(GenerateNaming.CurrentVersion()),
            "// <auto-generated/>",
            "",
        };

        foreach (var heading in UsingLines(data.Namespace, data.MessageInterface, data.Usings))
        {
            lines.Add(heading);
        }

        if (lines[^1].Length > 0)
        {
            lines.Add("");
        }

        lines.Add($"namespace {data.Namespace};");
        lines.Add("");
        lines.AddRange(DocLines(data.Summary, data.MessageType));

        if (data.Tenant is { } tenant)
        {
            lines.Add($"/// <param name=\"{tenant.Property}\">The tenant the call acts in.</param>");
        }

        foreach (var input in data.Inputs)
        {
            if (input.Meaning is { Length: > 0 } meaning)
            {
                lines.Add($"/// <param name=\"{input.Property}\">{GenerateNaming.EscapeXml(FlatOf(meaning))}</param>");
            }
        }

        if (data.Paging is { } paging)
        {
            if (paging.Cursor is { Length: > 0 } cursor)
            {
                lines.Add($"/// <param name=\"Cursor\">{GenerateNaming.EscapeXml(FlatOf(cursor))}</param>");
            }

            if (paging.Offset is { Length: > 0 } offset)
            {
                lines.Add($"/// <param name=\"Offset\">{GenerateNaming.EscapeXml(FlatOf(offset))}</param>");
            }

            lines.Add("/// <param name=\"Limit\">The rows per page.</param>");
        }

        var visibility = data.IsPublic ? "public" : "internal";
        var parameters = string.Join(", ", ParametersOf(data));
        var marker = data.MessageInterface.Length > 0 ? $" : {SimpleName(data.MessageInterface)}<{data.ResultType}>" : "";

        if (data.Key is null)
        {
            lines.Add($"{visibility} sealed partial record {data.MessageType}({parameters}){marker};");

            return string.Join('\n', lines) + "\n";
        }

        lines.Add($"{visibility} sealed partial record {data.MessageType}({parameters}){marker}");
        lines.Add("{");
        lines.Add("    /// <summary>The idempotency key of this command.</summary>");
        lines.Add($"    public string IdempotencyKey => {data.Key.Expression};");
        lines.Add("}");

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>The message type name: the use case in PascalCase with a Command or Query suffix.</summary>
    /// <param name="useCase">The use-case name the use-case identifier carries.</param>
    /// <param name="kind">The use-case kind: command or query.</param>
    /// <returns>The message type name.</returns>
    public static string MessageTypeName(string useCase, string kind) =>
        GenerateNaming.ConstName(useCase) + (kind == "query" ? "Query" : "Command");

    /// <summary>The result type name: the use case with its kind and a Result suffix, or the use case with a Result suffix for a public use case.</summary>
    /// <param name="useCase">The use-case name the use-case identifier carries.</param>
    /// <param name="kind">The use-case kind: command or query.</param>
    /// <param name="isPublic">True when the use case is public.</param>
    /// <returns>The result type name.</returns>
    public static string ResultTypeName(string useCase, string kind, bool isPublic) =>
        isPublic
            ? GenerateNaming.ConstName(useCase) + "Result"
            : GenerateNaming.ConstName(useCase) + (kind == "query" ? "QueryResult" : "CommandResult");

    /// <summary>The positional parameters of the message: the tenant key first, each input, and the paging members with their defaults.</summary>
    /// <param name="data">The use-case message the plan renders.</param>
    /// <returns>The parameter texts in order.</returns>
    private static List<string> ParametersOf(MessageData data)
    {
        var parameters = new List<string>();

        if (data.Tenant is { } tenant)
        {
            parameters.Add($"{tenant.Type} {tenant.Property}");
        }

        parameters.AddRange(data.Inputs.Select(input => $"{input.Type} {input.Property}"));

        if (data.Paging is { } paging)
        {
            if (paging.Cursor is { Length: > 0 })
            {
                parameters.Add("string? Cursor = null");
            }

            if (paging.Offset is { Length: > 0 })
            {
                parameters.Add("int Offset = 0");
            }

            parameters.Add($"int Limit = {paging.DefaultLimit}");
        }

        return parameters;
    }

    /// <summary>The using lines the file opens with: the interface namespace with the target usings, ordered, without the file's own namespace or an enclosing one.</summary>
    /// <param name="namespace">The C# namespace of the generated record.</param>
    /// <param name="messageInterface">The LiteBus message interface as the target declares it, or empty.</param>
    /// <param name="usings">The C# namespaces the target declares.</param>
    /// <returns>The using lines in ordinal order.</returns>
    private static List<string> UsingLines(string @namespace, string messageInterface, IReadOnlyList<string> usings)
    {
        var names = new SortedSet<string>(StringComparer.Ordinal);

        if (messageInterface.Contains('.', StringComparison.Ordinal)
            && messageInterface[..messageInterface.LastIndexOf('.')] is { Length: > 0 } interfaceNamespace)
        {
            names.Add(interfaceNamespace);
        }

        foreach (var usingNamespace in usings)
        {
            if (usingNamespace.Length > 0)
            {
                names.Add(usingNamespace);
            }
        }

        names.RemoveWhere(candidate =>
            candidate == @namespace || @namespace.StartsWith(candidate + ".", StringComparison.Ordinal));

        return [.. names.Select(candidate => $"using {candidate};")];
    }

    /// <summary>The documentation lines of the message: its summary, or its type name when the record states no summary.</summary>
    /// <param name="summary">The summary the record states, or null.</param>
    /// <param name="messageType">The message type name.</param>
    /// <returns>The documentation lines.</returns>
    private static List<string> DocLines(string? summary, string messageType) =>
        summary is { Length: > 0 } stated
            ? GenerateNaming.XmlDocLines(FlatOf(stated), "")
            : [$"/// <summary>The {messageType} message.</summary>"];

    /// <summary>The simple interface name: the declared interface type after its last dot.</summary>
    /// <param name="messageInterface">The LiteBus message interface as the target declares it.</param>
    /// <returns>The simple type name.</returns>
    private static string SimpleName(string messageInterface) =>
        messageInterface.Contains('.', StringComparison.Ordinal)
            ? messageInterface[(messageInterface.LastIndexOf('.') + 1)..]
            : messageInterface;

    /// <summary>One line of documentation text: newlines read as spaces.</summary>
    /// <param name="text">The documentation text.</param>
    /// <returns>The flattened text.</returns>
    private static string FlatOf(string text) =>
        text.Replace("\r\n", " ", StringComparison.Ordinal).Replace('\n', ' ').Replace('\r', ' ');
}
