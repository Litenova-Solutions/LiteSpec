using LiteSpec.Cli.Model.Refusals;

namespace LiteSpec.Cli.Generate;

/// <summary>
///     Renders the refusal codes the records declare: per module a C# constant class, and
///     for a TypeScript stack one file with the codes, their union type, and the sentences
///     the refusal results state.
/// </summary>
/// <follows>litespec/core/model#generate-record-determined-code-from-the-records</follows>
static class RefusalCodesRenderer
{
    /// <summary>
    ///     Renders one module's refusal codes as C#: a public static class with one
    ///     public const string per refusal, named from the refusal key in PascalCase
    ///     and documented with the refusal's meaning.
    /// </summary>
    /// <param name="module">The record module name.</param>
    /// <param name="entries">The module's declared refusals.</param>
    /// <param name="namespace">The C# namespace of the generated class.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(string module, IReadOnlyList<RefusalEntry> entries, string @namespace)
    {
        var name = GenerateNaming.ModulePascal(module);
        var lines = new List<string>
        {
            GenerateNaming.HeaderLineFor(GenerateNaming.CurrentVersion()),
            "// <auto-generated/>",
            "",
            $"namespace {@namespace};",
            "",
            $"/// <summary>The refusal codes the {module} module declares.</summary>",
            $"public static class {name}RefusalCodes",
            "{",
        };

        foreach (var entry in entries.OrderBy(entry => entry.Code, StringComparer.Ordinal))
        {
            var key = entry.Code.Contains('.', StringComparison.Ordinal)
                ? entry.Code[(entry.Code.IndexOf('.', StringComparison.Ordinal) + 1)..]
                : entry.Code;

            lines.AddRange(GenerateNaming.XmlDocLines(entry.Meaning, "    "));
            lines.Add($"    public const string {GenerateNaming.ConstName(key)} = \"{GenerateNaming.EscapeLiteral(entry.Code)}\";");
        }

        lines.Add("}");

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>
    ///     Renders every refusal code as TypeScript: a const object of codes, their union
    ///     type, and a map from each code to the English sentence its refusal results state.
    /// </summary>
    /// <param name="entries">Every declared refusal.</param>
    /// <param name="sentences">The English sentence by refusal code, for the codes whose results state one.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderTypeScript(
        IReadOnlyList<RefusalEntry> entries,
        IReadOnlyDictionary<string, string> sentences)
    {
        var ordered = entries.OrderBy(entry => entry.Code, StringComparer.Ordinal).ToList();
        var lines = new List<string>
        {
            GenerateNaming.HeaderLineFor(GenerateNaming.CurrentVersion()),
            "// <auto-generated/>",
            "",
            "export const refusalCodes = {",
        };

        foreach (var entry in ordered)
        {
            var key = entry.Code.Contains('.', StringComparison.Ordinal)
                ? entry.Code[(entry.Code.IndexOf('.', StringComparison.Ordinal) + 1)..]
                : entry.Code;

            lines.Add($"  {GenerateNaming.ModulePascal(entry.Module)}{GenerateNaming.ConstName(key)}: \"{GenerateNaming.EscapeLiteral(entry.Code)}\",");
        }

        lines.Add("} as const;");
        lines.Add("export type RefusalCode = (typeof refusalCodes)[keyof typeof refusalCodes];");
        lines.Add("export const refusalSentences: Record<RefusalCode, string> = {");

        foreach (var entry in ordered)
        {
            if (sentences.TryGetValue(entry.Code, out var sentence))
            {
                lines.Add($"  \"{GenerateNaming.EscapeLiteral(entry.Code)}\": \"{GenerateNaming.EscapeLiteral(sentence)}\",");
            }
        }

        lines.Add("};");

        return string.Join('\n', lines) + "\n";
    }
}
