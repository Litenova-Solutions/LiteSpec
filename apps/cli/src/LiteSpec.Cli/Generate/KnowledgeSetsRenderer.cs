using System.Globalization;
using System.Text.Json;
using LiteSpec.Model;

namespace LiteSpec.Cli.Generate;

/// <summary>
///     Renders the knowledge sets the records declare as C#: per area and variant one
///     static partial class per table, with a Rows list building each row of the variant
///     through the model constructor, or the factory the table names, with named arguments
///     from the column mapping, or a Value holding the one row of a singleton table.
/// </summary>
/// <follows>litespec/core/model#generate-record-determined-code-from-the-records</follows>
static class KnowledgeSetsRenderer
{
    /// <summary>One column-to-parameter mapping of a reference-data table, as the generator reads it.</summary>
    /// <param name="Column">The row field the parameter reads, the list field of a list entry, or empty when the entry builds a nested object.</param>
    /// <param name="Parameter">The row parameter name.</param>
    /// <param name="Rendering">How the column value renders: string, number, boolean, date, money, decimal, key, member, case, object, map or list.</param>
    /// <param name="Type">The qualified model type of a money, key, member, case or object column, or of the items of a list, or null when the entry states none.</param>
    /// <param name="Factory">The static factory building a typed key or the key items of a list.</param>
    /// <param name="Currency">The three-letter currency code of a money column or of the money items of a list, or null when the entry states none.</param>
    /// <param name="Literals">The literal by row value of a map column, or by item of mapped items.</param>
    /// <param name="Nested">The sub-columns building a nested object or each object item, or empty when the entry states none.</param>
    /// <param name="Items">How each item of a list entry renders, or empty when the entry is no list.</param>
    public sealed record ColumnMapping(
        string Column,
        string Parameter,
        string Rendering,
        string? Type,
        string Factory,
        string? Currency,
        IReadOnlyDictionary<string, string> Literals,
        IReadOnlyList<ColumnMapping> Nested,
        string Items = "");

    /// <summary>
    ///     Renders one variant's rows of one table as C#: a public static partial class with a
    ///     Rows list holding one constructor call per row, or one factory call when the table
    ///     names a factory, the rows in key order. A row value the mapping cannot build renders
    ///     as a literal, and the column check reports it; a column the row does not state renders
    ///     as null, as does a nested object none of whose fields the row states, while a stated
    ///     list renders its items in written order and an empty list renders empty.
    /// </summary>
    /// <param name="area">The knowledge area name.</param>
    /// <param name="variant">The variant the rows belong to.</param>
    /// <param name="table">The table name, the name segment of the record identifier.</param>
    /// <param name="recordId">The identifier of the record declaring the table.</param>
    /// <param name="rowType">The qualified model row type.</param>
    /// <param name="factory">The static factory method building one row, or null when rows build through the constructor.</param>
    /// <param name="mappings">The column mappings in written order.</param>
    /// <param name="rows">The variant's row objects.</param>
    /// <param name="namespace">The C# namespace of the generated class.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(
        string area,
        string variant,
        string table,
        string recordId,
        string rowType,
        string? factory,
        IReadOnlyList<ColumnMapping> mappings,
        IReadOnlyList<JsonElement> rows,
        string @namespace)
    {
        var name = GenerateNaming.ConstName(variant) + GenerateNaming.ConstName(table);
        var shortRow = ShortName(rowType);
        var ordered = rows
            .OrderBy(row => RowText(row, RecordFields.Key) ?? "", StringComparer.Ordinal)
            .ThenBy(row => RowText(row, RecordFields.EffectiveFrom) ?? "", StringComparer.Ordinal)
            .ToList();
        var used = new HashSet<string>(StringComparer.Ordinal);
        var dateUsed = false;
        var blocks = ordered
            .Select(row => RenderRow(row, shortRow, factory, mappings, used, ref dateUsed))
            .ToList();

        if (NamespaceOf(rowType) is { } rowNamespace)
        {
            used.Add(rowNamespace);
        }

        var lines = new List<string>
        {
            GenerateNaming.HeaderLineFor(GenerateNaming.CurrentVersion()),
            "// <auto-generated/>",
        };

        foreach (var heading in UsingLines(@namespace, used, dateUsed, collections: true))
        {
            lines.Add(heading);
        }

        lines.Add("");
        lines.Add($"namespace {@namespace};");
        lines.Add("");
        lines.Add($"/// <summary>The {table} rows of the {variant} variant, from {recordId}.</summary>");
        lines.Add($"public static partial class {name}");
        lines.Add("{");
        lines.Add($"    /// <summary>Every {table} row of the {variant} variant in key order.</summary>");
        lines.Add($"    public static IReadOnlyList<{shortRow}> Rows {{ get; }} = new {shortRow}[]");
        lines.Add("    {");

        for (var index = 0; index < blocks.Count; index++)
        {
            foreach (var line in blocks[index])
            {
                lines.Add(line);
            }
        }

        lines.Add("    };");
        lines.Add("}");

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>
    ///     Renders one variant's value of one singleton table as C#: a public static partial
    ///     class with a Value holding the constructor call for the variant's row, or the factory
    ///     call when the table names a factory. A row value the mapping cannot build renders as
    ///     a literal, and the column check reports it; a column the row does not state renders
    ///     as null, as does a nested object none of whose fields the row states, while a stated
    ///     list renders its items in written order and an empty list renders empty.
    /// </summary>
    /// <param name="area">The knowledge area name.</param>
    /// <param name="variant">The variant the row belongs to.</param>
    /// <param name="table">The table name, the name segment of the record identifier.</param>
    /// <param name="recordId">The identifier of the record declaring the table.</param>
    /// <param name="rowType">The qualified model row type.</param>
    /// <param name="factory">The static factory method building one row, or null when rows build through the constructor.</param>
    /// <param name="mappings">The column mappings in written order.</param>
    /// <param name="row">The variant's row object.</param>
    /// <param name="namespace">The C# namespace of the generated class.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderSingletonDotnet(
        string area,
        string variant,
        string table,
        string recordId,
        string rowType,
        string? factory,
        IReadOnlyList<ColumnMapping> mappings,
        JsonElement row,
        string @namespace)
    {
        var name = GenerateNaming.ConstName(variant) + GenerateNaming.ConstName(table);
        var shortRow = ShortName(rowType);
        var used = new HashSet<string>(StringComparer.Ordinal);
        var dateUsed = false;
        var head = factory is { Length: > 0 } ? $"{shortRow}.{factory}" : $"new {shortRow}";
        var call = mappings.Count == 0
            ? new List<string> { $"    public static {shortRow} Value {{ get; }} = {head}();" }
            : CallLines(
                $"    public static {shortRow} Value {{ get; }} = {head}(",
                "        ",
                "    );",
                mappings,
                row,
                used,
                ref dateUsed);

        if (NamespaceOf(rowType) is { } rowNamespace)
        {
            used.Add(rowNamespace);
        }

        var lines = new List<string>
        {
            GenerateNaming.HeaderLineFor(GenerateNaming.CurrentVersion()),
            "// <auto-generated/>",
        };

        foreach (var heading in UsingLines(@namespace, used, dateUsed, collections: false))
        {
            lines.Add(heading);
        }

        lines.Add("");
        lines.Add($"namespace {@namespace};");
        lines.Add("");
        lines.Add($"/// <summary>The {table} value of the {variant} variant, from {recordId}.</summary>");
        lines.Add($"public static partial class {name}");
        lines.Add("{");
        lines.Add($"    /// <summary>The {table} value of the {variant} variant.</summary>");
        lines.AddRange(call);
        lines.Add("}");

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>Renders one row: a constructor call with one named argument per mapping, in mapping order, or a factory call when the table names one.</summary>
    /// <param name="row">The row object as written.</param>
    /// <param name="shortRow">The model row type name without its namespace.</param>
    /// <param name="factory">The static factory method building one row, or null when rows build through the constructor.</param>
    /// <param name="mappings">The column mappings in written order.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <param name="dateUsed">Whether a rendered argument builds a date, set in place.</param>
    /// <returns>The row lines.</returns>
    private static List<string> RenderRow(
        JsonElement row,
        string shortRow,
        string? factory,
        IReadOnlyList<ColumnMapping> mappings,
        HashSet<string> used,
        ref bool dateUsed)
    {
        var head = factory is { Length: > 0 } ? $"{shortRow}.{factory}" : $"new {shortRow}";

        if (mappings.Count == 0)
        {
            return [$"        {head}(),"];
        }

        return CallLines($"        {head}(", "            ", "        ),", mappings, row, used, ref dateUsed);
    }

    /// <summary>Renders one constructor or factory call: the opening line, one named argument per mapping in mapping order, and the closing line.</summary>
    /// <param name="open">The line opening the call.</param>
    /// <param name="argIndent">The indentation opening each argument.</param>
    /// <param name="close">The line closing the call.</param>
    /// <param name="mappings">The column mappings in written order.</param>
    /// <param name="row">The row object as written.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <param name="dateUsed">Whether a rendered argument builds a date, set in place.</param>
    /// <returns>The call lines.</returns>
    private static List<string> CallLines(
        string open,
        string argIndent,
        string close,
        IReadOnlyList<ColumnMapping> mappings,
        JsonElement row,
        HashSet<string> used,
        ref bool dateUsed)
    {
        var lines = new List<string> { open };

        for (var index = 0; index < mappings.Count; index++)
        {
            var comma = index + 1 < mappings.Count ? "," : "";
            lines.AddRange(ArgumentLines(mappings[index], row, argIndent, comma, used, ref dateUsed));
        }

        lines.Add(close);

        return lines;
    }

    /// <summary>Renders one named argument: one line for a column value, or one block for a nested object or a list of objects.</summary>
    /// <param name="mapping">The column mapping.</param>
    /// <param name="row">The row object as written.</param>
    /// <param name="indent">The indentation opening the argument.</param>
    /// <param name="comma">The comma closing the argument, or empty for the last argument of its call.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <param name="dateUsed">Whether a rendered argument builds a date, set in place.</param>
    /// <returns>The argument lines.</returns>
    private static List<string> ArgumentLines(
        ColumnMapping mapping,
        JsonElement row,
        string indent,
        string comma,
        HashSet<string> used,
        ref bool dateUsed)
    {
        if (mapping.Rendering == "object")
        {
            return ObjectLines(mapping, row, indent, comma, used, ref dateUsed);
        }

        if (mapping.Rendering == "list")
        {
            return ListLines(mapping, row, indent, comma, used, ref dateUsed);
        }

        return [$"{indent}{mapping.Parameter}: {Expression(mapping, row, used, ref dateUsed)}{comma}"];
    }

    /// <summary>Renders one nested object: a constructor call over its sub-columns, or null when the row states none of its fields.</summary>
    /// <param name="mapping">The object mapping with its sub-columns.</param>
    /// <param name="row">The row object as written.</param>
    /// <param name="indent">The indentation opening the argument.</param>
    /// <param name="comma">The comma closing the argument, or empty for the last argument of its call.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <param name="dateUsed">Whether a rendered argument builds a date, set in place.</param>
    /// <returns>The argument lines.</returns>
    private static List<string> ObjectLines(
        ColumnMapping mapping,
        JsonElement row,
        string indent,
        string comma,
        HashSet<string> used,
        ref bool dateUsed) =>
        ObjectConstructionLines(mapping, row, $"{indent}{mapping.Parameter}: ", indent, comma, used, ref dateUsed);

    /// <summary>Renders one list: its items in written order in a collection expression, or null when the row does not state it.</summary>
    /// <param name="mapping">The list mapping with its item rendering and, for object items, its sub-columns.</param>
    /// <param name="row">The row object as written.</param>
    /// <param name="indent">The indentation opening the argument.</param>
    /// <param name="comma">The comma closing the argument, or empty for the last argument of its call.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <param name="dateUsed">Whether a rendered argument builds a date, set in place.</param>
    /// <returns>The argument lines.</returns>
    private static List<string> ListLines(
        ColumnMapping mapping,
        JsonElement row,
        string indent,
        string comma,
        HashSet<string> used,
        ref bool dateUsed)
    {
        if (!row.TryGetProperty(mapping.Column, out var value))
        {
            return [$"{indent}{mapping.Parameter}: null{comma}"];
        }

        if (value.ValueKind != JsonValueKind.Array)
        {
            return [$"{indent}{mapping.Parameter}: {Literal(value)}{comma}"];
        }

        var items = value.EnumerateArray().ToList();

        if (items.Count == 0 || mapping.Items != "object")
        {
            var rendered = new List<string>();

            foreach (var item in items)
            {
                rendered.Add(ValueExpression(mapping, mapping.Items, item, used, ref dateUsed));
            }

            return [$"{indent}{mapping.Parameter}: [{string.Join(", ", rendered)}]{comma}"];
        }

        var lines = new List<string> { $"{indent}{mapping.Parameter}: [" };
        var nested = indent + "    ";

        for (var index = 0; index < items.Count; index++)
        {
            var itemComma = index + 1 < items.Count ? "," : "";
            lines.AddRange(ObjectConstructionLines(mapping, items[index], nested, nested, itemComma, used, ref dateUsed));
        }

        lines.Add($"{indent}]{comma}");

        return lines;
    }

    /// <summary>Renders one nested object construction: a literal when the map is no object, null when the model type is missing or the map states none of its fields, an empty construction without sub-columns, else a constructor call over the sub-columns.</summary>
    /// <param name="mapping">The object mapping with its sub-columns, or the list mapping with the sub-columns building each object item.</param>
    /// <param name="map">The map the sub-columns read: the row, or one list item.</param>
    /// <param name="prefix">The text opening the construction: the indentation with the parameter, or the item indentation.</param>
    /// <param name="closingIndent">The indentation closing the construction.</param>
    /// <param name="comma">The comma closing the construction, or empty for the last of its call.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <param name="dateUsed">Whether a rendered argument builds a date, set in place.</param>
    /// <returns>The construction lines.</returns>
    private static List<string> ObjectConstructionLines(
        ColumnMapping mapping,
        JsonElement map,
        string prefix,
        string closingIndent,
        string comma,
        HashSet<string> used,
        ref bool dateUsed)
    {
        if (map.ValueKind != JsonValueKind.Object)
        {
            return [$"{prefix}{Literal(map)}{comma}"];
        }

        if (mapping.Type is not { Length: > 0 } || !AnyStated(mapping, map))
        {
            return [$"{prefix}null{comma}"];
        }

        if (NamespaceOf(mapping.Type) is { } space)
        {
            used.Add(space);
        }

        if (mapping.Nested.Count == 0)
        {
            return [$"{prefix}new {ShortName(mapping.Type)}(){comma}"];
        }

        var lines = new List<string> { $"{prefix}new {ShortName(mapping.Type)}(" };
        var nested = closingIndent + "    ";

        for (var index = 0; index < mapping.Nested.Count; index++)
        {
            var nestedComma = index + 1 < mapping.Nested.Count ? "," : "";
            lines.AddRange(ArgumentLines(mapping.Nested[index], map, nested, nestedComma, used, ref dateUsed));
        }

        lines.Add($"{closingIndent}){comma}");

        return lines;
    }

    /// <summary>Whether the map states any field the mapping reads: its own column, any leaf beneath a nested object, or any sub-column field of an object item.</summary>
    /// <param name="mapping">The column mapping.</param>
    /// <param name="map">The map the mapping reads: the row, or one list item.</param>
    /// <returns>True when the map states at least one field the mapping reads.</returns>
    private static bool AnyStated(ColumnMapping mapping, JsonElement map)
    {
        if (mapping.Rendering == "object" || (mapping.Rendering == "list" && mapping.Items == "object"))
        {
            return mapping.Nested.Any(child => AnyStated(child, map));
        }

        return mapping.Column.Length > 0 && map.TryGetProperty(mapping.Column, out _);
    }

    /// <summary>Renders one argument: the row column under the mapping's rendering, null when the row does not state it.</summary>
    /// <param name="mapping">The column mapping.</param>
    /// <param name="row">The row object as written.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <param name="dateUsed">Whether a rendered argument builds a date, set in place.</param>
    /// <returns>The argument expression.</returns>
    private static string Expression(ColumnMapping mapping, JsonElement row, HashSet<string> used, ref bool dateUsed)
    {
        if (!row.TryGetProperty(mapping.Column, out var value))
        {
            return "null";
        }

        return ValueExpression(mapping, mapping.Rendering, value, used, ref dateUsed);
    }

    /// <summary>Renders one value under one rendering: a column value, or one item of a list under the item rendering.</summary>
    /// <param name="mapping">The column mapping holding the model type, factory, currency and value map.</param>
    /// <param name="rendering">The rendering the value renders under.</param>
    /// <param name="value">The value as written.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <param name="dateUsed">Whether a rendered argument builds a date, set in place.</param>
    /// <returns>The value expression.</returns>
    private static string ValueExpression(ColumnMapping mapping, string rendering, JsonElement value, HashSet<string> used, ref bool dateUsed) =>
        rendering switch
        {
            "number" => value.ValueKind == JsonValueKind.Number ? value.GetRawText() : Literal(value),
            "boolean" => value.ValueKind switch
            {
                JsonValueKind.True => "true",
                JsonValueKind.False => "false",
                _ => Literal(value),
            },
            "date" => DateExpression(value, ref dateUsed),
            "money" => MoneyExpression(mapping, value, used),
            "decimal" => DecimalExpression(value),
            "key" => KeyExpression(mapping, value, used),
            "member" => MemberExpression(mapping, value, used),
            "case" => CaseExpression(mapping, value, used),
            "map" => MapExpression(mapping, value),
            _ => Literal(value),
        };

    /// <summary>Renders one value as a quoted literal: a string as written, a number or boolean as its raw text.</summary>
    /// <param name="value">The row value as written.</param>
    /// <returns>The literal expression.</returns>
    private static string Literal(JsonElement value) => value.ValueKind switch
    {
        JsonValueKind.String => $"\"{GenerateNaming.EscapeLiteral(value.GetString() ?? "")}\"",
        JsonValueKind.Number or JsonValueKind.True or JsonValueKind.False => $"\"{value.GetRawText()}\"",
        _ => "null",
    };

    /// <summary>Renders one date column as a date construction, or a literal when the value states no ISO date.</summary>
    /// <param name="value">The row value as written.</param>
    /// <param name="dateUsed">Whether a rendered argument builds a date, set in place.</param>
    /// <returns>The date expression.</returns>
    private static string DateExpression(JsonElement value, ref bool dateUsed)
    {
        if (value.ValueKind == JsonValueKind.String
            && value.GetString() is { } text
            && DateOnly.TryParseExact(text, "yyyy-MM-dd", CultureInfo.InvariantCulture, DateTimeStyles.None, out var date))
        {
            dateUsed = true;

            return $"new DateOnly({date.Year}, {date.Month}, {date.Day})";
        }

        return Literal(value);
    }

    /// <summary>Renders one money column through the model money type, or a literal when the entry or value states less.</summary>
    /// <param name="mapping">The column mapping.</param>
    /// <param name="value">The row value as written.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <returns>The money expression.</returns>
    private static string MoneyExpression(ColumnMapping mapping, JsonElement value, HashSet<string> used)
    {
        if (mapping.Type is { } type
            && NamespaceOf(type) is { } space
            && mapping.Currency is { Length: 3 } currency
            && value.ValueKind == JsonValueKind.Number
            && value.TryGetDecimal(out var amount))
        {
            used.Add(space);

            return $"{ShortName(type)}.Create({amount.ToString(CultureInfo.InvariantCulture)}m, \"{currency}\")";
        }

        return Literal(value);
    }

    /// <summary>Renders one decimal column with its suffix, or a literal when the value states no number.</summary>
    /// <param name="value">The row value as written.</param>
    /// <returns>The decimal expression.</returns>
    private static string DecimalExpression(JsonElement value)
    {
        if (value.ValueKind == JsonValueKind.Number && value.TryGetDecimal(out var amount))
        {
            return $"{amount.ToString(CultureInfo.InvariantCulture)}m";
        }

        return Literal(value);
    }

    /// <summary>Renders one typed key through the model's factory with the key text, or a literal when the entry or value states less.</summary>
    /// <param name="mapping">The column mapping.</param>
    /// <param name="value">The row value as written.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <returns>The key expression.</returns>
    private static string KeyExpression(ColumnMapping mapping, JsonElement value, HashSet<string> used)
    {
        if (mapping.Type is { } type
            && NamespaceOf(type) is { } space
            && value.ValueKind == JsonValueKind.String
            && value.GetString() is { } text)
        {
            used.Add(space);

            var factory = mapping.Factory.Length > 0 ? mapping.Factory : "From";

            return $"{ShortName(type)}.{factory}(\"{GenerateNaming.EscapeLiteral(text)}\")";
        }

        return Literal(value);
    }

    /// <summary>Renders one closed-set value as the model's member of its name, or a literal when the entry or value states less.</summary>
    /// <param name="mapping">The column mapping.</param>
    /// <param name="value">The row value as written.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <returns>The member expression.</returns>
    private static string MemberExpression(ColumnMapping mapping, JsonElement value, HashSet<string> used)
    {
        if (mapping.Type is { } type
            && NamespaceOf(type) is { } space
            && value.ValueKind == JsonValueKind.String
            && value.GetString() is { } text)
        {
            used.Add(space);

            return $"{ShortName(type)}.{GenerateNaming.ConstName(text)}";
        }

        return Literal(value);
    }

    /// <summary>Renders one closed-set value as a new case of its nested set, or a literal when the entry or value states less.</summary>
    /// <param name="mapping">The column mapping.</param>
    /// <param name="value">The row value as written.</param>
    /// <param name="used">The model namespaces the rendered arguments use, appended in place.</param>
    /// <returns>The case expression.</returns>
    private static string CaseExpression(ColumnMapping mapping, JsonElement value, HashSet<string> used)
    {
        if (mapping.Type is { } type
            && NamespaceOf(type) is { } space
            && value.ValueKind == JsonValueKind.String
            && value.GetString() is { } text)
        {
            used.Add(space);

            return $"new {ShortName(type)}.{GenerateNaming.ConstName(text)}()";
        }

        return Literal(value);
    }

    /// <summary>Renders one mapped column as its mapped literal, or the raw value when the map skips it.</summary>
    /// <param name="mapping">The column mapping.</param>
    /// <param name="value">The row value as written.</param>
    /// <returns>The mapped literal.</returns>
    private static string MapExpression(ColumnMapping mapping, JsonElement value)
    {
        if (value.ValueKind == JsonValueKind.String
            && value.GetString() is { } text
            && mapping.Literals.TryGetValue(text, out var mapped))
        {
            return $"\"{GenerateNaming.EscapeLiteral(mapped)}\"";
        }

        return Literal(value);
    }

    /// <summary>The using lines the file needs: the collections for a row list, System for dates, and each used model namespace but its own.</summary>
    /// <param name="namespace">The C# namespace of the generated class.</param>
    /// <param name="used">The model namespaces the rendered arguments use.</param>
    /// <param name="dateUsed">Whether a rendered argument builds a date.</param>
    /// <param name="collections">Whether the file holds a row list.</param>
    /// <returns>The using lines in order.</returns>
    private static List<string> UsingLines(string @namespace, HashSet<string> used, bool dateUsed, bool collections)
    {
        var lines = new List<string>();

        if (dateUsed)
        {
            lines.Add("using System;");
        }

        if (collections)
        {
            lines.Add("using System.Collections.Generic;");
        }

        foreach (var space in used.Where(candidate => candidate != @namespace).OrderBy(candidate => candidate, StringComparer.Ordinal))
        {
            lines.Add($"using {space};");
        }

        return lines;
    }

    /// <summary>The text of one string field of a row, or null when the row states none.</summary>
    /// <param name="row">The row object as written.</param>
    /// <param name="field">The field name.</param>
    /// <returns>The field text, or null when the row states no string field.</returns>
    private static string? RowText(JsonElement row, string field) =>
        row.TryGetProperty(field, out var value) && value.ValueKind == JsonValueKind.String ? value.GetString() : null;

    /// <summary>The type name without its namespace: the text after the last dot, or the whole name when it holds none.</summary>
    /// <param name="type">The type name as written.</param>
    /// <returns>The short type name.</returns>
    private static string ShortName(string type)
    {
        var dot = type.LastIndexOf('.');

        return dot >= 0 ? type[(dot + 1)..] : type;
    }

    /// <summary>The namespace of a qualified type name, or null when the name holds no namespace.</summary>
    /// <param name="type">The type name as written.</param>
    /// <returns>The namespace, or null when the name is unqualified.</returns>
    private static string? NamespaceOf(string type)
    {
        var dot = type.LastIndexOf('.');

        return dot > 0 && dot < type.Length - 1 ? type[..dot] : null;
    }
