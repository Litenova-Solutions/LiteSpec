using LiteSpec.Model;

namespace LiteSpec.Cli.Generate;

/// <summary>
///     Renders the result of one use case as C#: a partial record from its output, with one
///     positional property per field, a nested record per output group when the output holds
///     several, a row type per multi-field list, and the next cursor when the query pages.
///     A hand-written sibling file may add members to the generated type.
/// </summary>
/// <follows>litespec/core/model#generate-record-determined-code-from-the-records</follows>
static class ResultsRenderer
{
    /// <summary>One output group of a multi-group result with its fields.</summary>
    /// <param name="Group">The group name the output states.</param>
    /// <param name="Property">The property name in PascalCase.</param>
    /// <param name="Fields">The group fields with their C# types, in written order.</param>
    public sealed record ResultGroup(
        string Group,
        string Property,
        IReadOnlyList<MessageFieldTypes.MappedField> Fields);

    /// <summary>One use-case result the plan renders.</summary>
    /// <param name="UseCaseId">The use case identifier.</param>
    /// <param name="Title">The use-case title the summary reads from.</param>
    /// <param name="ResultType">The result type name, such as ListLoansQueryResult.</param>
    /// <param name="Fields">The output fields with their C# types, in written order, or an empty list when the output holds several groups.</param>
    /// <param name="Groups">The output groups with their fields, in written order, or an empty list when the output holds no groups.</param>
    /// <param name="HasNextCursor">True when the query pages and the result carries the next cursor.</param>
    /// <param name="Namespace">The C# namespace of the generated record.</param>
    /// <param name="Usings">The C# namespaces the target declares for referenced identifier and value types.</param>
    /// <param name="IsPublic">True when the result answers a public use case from the Contracts project.</param>
    public sealed record ResultData(
        string UseCaseId,
        string Title,
        string ResultType,
        IReadOnlyList<MessageFieldTypes.MappedField> Fields,
        IReadOnlyList<ResultGroup> Groups,
        bool HasNextCursor,
        string Namespace,
        IReadOnlyList<string> Usings,
        bool IsPublic);

    /// <summary>One list row type the plan renders beside its result.</summary>
    /// <param name="RowType">The row type name the record states in rowType.</param>
    /// <param name="ListProperty">The list property the row belongs to.</param>
    /// <param name="Fields">The row fields with their C# types, in written order.</param>
    /// <param name="Namespace">The C# namespace of the generated record.</param>
    /// <param name="Usings">The C# namespaces the target declares for referenced identifier and value types.</param>
    /// <param name="IsPublic">True when the row answers a public use case from the Contracts project.</param>
    public sealed record RowData(
        string RowType,
        string ListProperty,
        IReadOnlyList<MessageFieldTypes.MappedField> Fields,
        string Namespace,
        IReadOnlyList<string> Usings,
        bool IsPublic);

    /// <summary>
    ///     Renders one use-case result as C#: a partial record with one positional property per
    ///     output field, or one property per output group with a nested record each when the
    ///     output holds several groups, and the next cursor when the query pages.
    /// </summary>
    /// <param name="data">The use-case result the plan renders.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(ResultData data)
    {
        var lines = new List<string>
        {
            GenerateNaming.HeaderLineFor(GenerateNaming.CurrentVersion()),
            "// <auto-generated/>",
            "",
        };

        foreach (var heading in UsingLines(data.Namespace, data.Usings))
        {
            lines.Add(heading);
        }

        if (lines[^1].Length > 0)
        {
            lines.Add("");
        }

        lines.Add($"namespace {data.Namespace};");
        lines.Add("");
        lines.Add($"/// <summary>The {data.Title} result.</summary>");

        foreach (var field in data.Fields)
        {
            if (field.Meaning is { Length: > 0 } meaning)
            {
                lines.Add($"/// <param name=\"{field.Property}\">{GenerateNaming.EscapeXml(FlatOf(meaning))}</param>");
            }
        }

        foreach (var group in data.Groups)
        {
            lines.Add($"/// <param name=\"{group.Property}\">The {group.Group} group.</param>");
        }

        if (data.HasNextCursor)
        {
            lines.Add("/// <param name=\"NextCursor\">The cursor of the next page, when another page follows.</param>");
        }

        var visibility = data.IsPublic ? "public" : "internal";
        var parameters = string.Join(", ", ParametersOf(data));

        if (data.Groups.Count == 0)
        {
            lines.Add($"{visibility} sealed partial record {data.ResultType}({parameters});");

            return string.Join('\n', lines) + "\n";
        }

        lines.Add($"{visibility} sealed partial record {data.ResultType}({parameters})");
        lines.Add("{");

        foreach (var group in data.Groups)
        {
            lines.Add($"    /// <summary>The {group.Group} group.</summary>");

            foreach (var field in group.Fields)
            {
                if (field.Meaning is { Length: > 0 } meaning)
                {
                    lines.Add($"    /// <param name=\"{field.Property}\">{GenerateNaming.EscapeXml(FlatOf(meaning))}</param>");
                }
            }

            lines.Add($"    public sealed partial record {group.Property}Group({string.Join(", ", group.Fields.Select(field => $"{field.Type} {field.Property}"))});");
        }

        lines.Add("}");

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>Renders one list row type as C#: a partial record with one positional property per row field.</summary>
    /// <param name="data">The list row type the plan renders.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderRowDotnet(RowData data)
    {
        var lines = new List<string>
        {
            GenerateNaming.HeaderLineFor(GenerateNaming.CurrentVersion()),
            "// <auto-generated/>",
            "",
        };

        foreach (var heading in UsingLines(data.Namespace, data.Usings))
        {
            lines.Add(heading);
        }

        if (lines[^1].Length > 0)
        {
            lines.Add("");
        }

        lines.Add($"namespace {data.Namespace};");
        lines.Add("");
        lines.Add($"/// <summary>One row of {data.ListProperty}.</summary>");

        foreach (var field in data.Fields)
        {
            if (field.Meaning is { Length: > 0 } meaning)
            {
                lines.Add($"/// <param name=\"{field.Property}\">{GenerateNaming.EscapeXml(FlatOf(meaning))}</param>");
            }
        }

        var visibility = data.IsPublic ? "public" : "internal";
        var parameters = string.Join(", ", data.Fields.Select(field => $"{field.Type} {field.Property}"));

        lines.Add($"{visibility} sealed partial record {data.RowType}({parameters});");

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>The positional parameters of the result: each field or group, with the next cursor last when the query pages.</summary>
    /// <param name="data">The use-case result the plan renders.</param>
    /// <returns>The parameter texts in order.</returns>
    private static List<string> ParametersOf(ResultData data)
    {
        var parameters = data.Fields.Select(field => $"{field.Type} {field.Property}").ToList();

        parameters.AddRange(data.Groups.Select(group => $"{group.Property}Group {group.Property}"));

        if (data.HasNextCursor)
        {
            parameters.Add("string? NextCursor = null");
        }

        return parameters;
    }

    /// <summary>The using lines the file opens with: the target usings, ordered, without the file's own namespace or an enclosing one.</summary>
    /// <param name="namespace">The C# namespace of the generated record.</param>
    /// <param name="usings">The C# namespaces the target declares.</param>
    /// <returns>The using lines in ordinal order.</returns>
    private static List<string> UsingLines(string @namespace, IReadOnlyList<string> usings)
    {
        var names = new SortedSet<string>(StringComparer.Ordinal);

        foreach (var usingNamespace in usings)
        {
            if (usingNamespace.Length > 0)
            {
                names.Add(usingNamespace);
            }
        }

        names.RemoveWhere(candidate =>
            candidate == @namespace || @namespace.StartsWith(candidate + ".", StringComparison.Ordinal));

        return [.. names.Select(candidate => $"using {candidate};")];
    }

    /// <summary>One line of documentation text: newlines read as spaces.</summary>
    /// <param name="text">The documentation text.</param>
    /// <returns>The flattened text.</returns>
    private static string FlatOf(string text) =>
        text.Replace("\r\n", " ", StringComparison.Ordinal).Replace('\n', ' ').Replace('\r', ' ');
}
