using LiteSpec.Model;

namespace LiteSpec.Cli.Generate;

/// <summary>
///     Renders the module events the records declare as C#: per event a public sealed
///     partial record with one positional property per published field in written order,
///     with types from the translated domain event. A hand-written sibling file may add
///     members, such as the factory building the event from its domain event.
/// </summary>
/// <follows>litespec/core/model#generate-record-determined-code-from-the-records</follows>
static class ModuleEventsRenderer
{
    /// <summary>One module event the plan renders.</summary>
    /// <param name="EventId">The module event identifier.</param>
    /// <param name="Name">The event name the event identifier carries.</param>
    /// <param name="Summary">The summary the record states, or null when the record states none.</param>
    /// <param name="Fields">The published fields with their C# types, in written order.</param>
    /// <param name="Namespace">The C# namespace of the generated record.</param>
    /// <param name="MarkerType">The marker interface as the target declares it, or empty when the target names none.</param>
    /// <param name="Usings">The C# namespaces the target declares for referenced identifier and value types.</param>
    /// <param name="Marks">The mark style the project declares.</param>
    public sealed record EventData(
        string EventId,
        string Name,
        string? Summary,
        IReadOnlyList<EventFieldTypes.MappedField> Fields,
        string Namespace,
        string MarkerType,
        IReadOnlyList<string> Usings,
        MarkStyle Marks);

    /// <summary>
    ///     Renders one module event as C#: a public sealed partial record named for the
    ///     fact, with one positional property per published field. A published multi-field
    ///     list nests its row record inside the event.
    /// </summary>
    /// <param name="data">The module event the plan renders.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(EventData data)
    {
        var type = TypeName(data.Name);
        var lines = new List<string>
        {
            GenerateNaming.HeaderLineFor(GenerateNaming.CurrentVersion()),
            "// <auto-generated/>",
            "",
        };

        foreach (var heading in UsingLines(data.Namespace, data.MarkerType, data.Usings))
        {
            lines.Add(heading);
        }

        if (lines[^1].Length > 0)
        {
            lines.Add("");
        }

        lines.Add($"namespace {data.Namespace};");
        lines.Add("");
        lines.AddRange(DocLines(data.Summary, data.Name));

        if (data.Marks == MarkStyle.Attribute)
        {
            lines.Add($"[Implements(\"{GenerateNaming.EscapeLiteral(data.EventId)}\")]");
        }
        else
        {
            lines.Add($"/// <implements>{GenerateNaming.EscapeXml(data.EventId)}</implements>");
        }

        var parameters = string.Join(", ", data.Fields.Select(field => $"{field.Type} {field.Property}"));
        var marker = data.MarkerType.Length > 0 ? $" : {SimpleName(data.MarkerType)}" : "";

        if (data.Fields.Any(field => field.Row.Count > 0))
        {
            lines.Add($"public sealed partial record {type}({parameters}){marker}");
            lines.Add("{");

            foreach (var field in data.Fields.Where(field => field.Row.Count > 0))
            {
                lines.Add($"    /// <summary>One row of {field.Property}.</summary>");

                foreach (var row in field.Row)
                {
                    if (field.Meanings.TryGetValue(row.Property, out var meaning))
                    {
                        lines.Add($"    /// <param name=\"{row.Property}\">{GenerateNaming.EscapeXml(FlatOf(meaning))}</param>");
                    }
                }

                lines.Add($"    public sealed partial record {field.Property}Row({string.Join(", ", field.Row.Select(row => $"{row.Type} {row.Property}"))});");
            }

            lines.Add("}");
        }
        else
        {
            lines.Add($"public sealed partial record {type}({parameters}){marker};");
        }

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>The module event type name: the fact in PascalCase with a ModuleEvent suffix.</summary>
    /// <param name="name">The event name the event identifier carries.</param>
    /// <returns>The module event type name.</returns>
    public static string TypeName(string name) =>
        GenerateNaming.ConstName(name) + "ModuleEvent";

    /// <summary>The fact folder holding one module event: On with the fact in PascalCase.</summary>
    /// <param name="name">The event name the event identifier carries.</param>
    /// <returns>The On fact folder name.</returns>
    public static string OnFolder(string name) =>
        "On" + GenerateNaming.ConstName(name);

    /// <summary>The using lines the file opens with: the marker namespace with the target usings, ordered, without the file's own namespace or an enclosing one.</summary>
    /// <param name="namespace">The C# namespace of the generated record.</param>
    /// <param name="markerType">The marker interface as the target declares it, or empty.</param>
    /// <param name="usings">The C# namespaces the target declares.</param>
    /// <returns>The using lines in ordinal order.</returns>
    private static List<string> UsingLines(string @namespace, string markerType, IReadOnlyList<string> usings)
    {
        var names = new SortedSet<string>(StringComparer.Ordinal);

        if (markerType.Contains('.', StringComparison.Ordinal)
            && markerType[..markerType.LastIndexOf('.')] is { Length: > 0 } markerNamespace)
        {
            names.Add(markerNamespace);
        }

        foreach (var usingNamespace in usings)
        {
            if (usingNamespace.Length > 0)
            {
                names.Add(usingNamespace);
            }
        }

        names.RemoveWhere(candidate =>
            candidate == @namespace || @namespace.StartsWith(candidate + ".", StringComparison.Ordinal));

        return [.. names.Select(candidate => $"using {candidate};")];
    }

    /// <summary>The documentation lines of the event: its summary, or its name when the record states no summary.</summary>
    /// <param name="summary">The summary the record states, or null.</param>
    /// <param name="name">The event name the event identifier carries.</param>
    /// <returns>The documentation lines.</returns>
    private static List<string> DocLines(string? summary, string name) =>
        summary is { Length: > 0 } stated
            ? GenerateNaming.XmlDocLines(FlatOf(stated), "")
            : [$"/// <summary>The {name.Replace('-', ' ')} module event.</summary>"];

    /// <summary>The simple marker name: the declared marker type after its last dot.</summary>
    /// <param name="markerType">The marker interface as the target declares it.</param>
    /// <returns>The simple type name.</returns>
    private static string SimpleName(string markerType) =>
        markerType.Contains('.', StringComparison.Ordinal)
            ? markerType[(markerType.LastIndexOf('.') + 1)..]
            : markerType;

    /// <summary>One line of documentation text: newlines read as spaces.</summary>
    /// <param name="text">The documentation text.</param>
    /// <returns>The flattened text.</returns>
    private static string FlatOf(string text) =>
        text.Replace("\r\n", " ", StringComparison.Ordinal).Replace('\n', ' ').Replace('\r', ' ');
}
