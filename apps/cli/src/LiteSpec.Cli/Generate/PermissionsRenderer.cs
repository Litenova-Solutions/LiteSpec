using LiteSpec.Cli.Model.Records;

namespace LiteSpec.Cli.Generate;

/// <summary>
///     Renders the permission ids the records declare: per module a C# constant class, and
///     for a TypeScript stack one file with the ids and their union type.
/// </summary>
/// <follows>litespec/core/model#generate-record-determined-code-from-the-records</follows>
static class PermissionsRenderer
{
    /// <summary>
    ///     Renders one module's permissions as C#: a public static class with one public
    ///     const string per permission, named from the permission name in PascalCase with
    ///     the permission id as its value, and documented with the permission's meaning.
    /// </summary>
    /// <param name="module">The record module name.</param>
    /// <param name="permissions">The module's permission records.</param>
    /// <param name="namespace">The C# namespace of the generated class.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(string module, IReadOnlyList<Record> permissions, string @namespace)
    {
        var name = GenerateNaming.ModulePascal(module);
        var lines = new List<string>
        {
            GenerateNaming.HeaderLine,
            "// <auto-generated/>",
            "",
            $"namespace {@namespace};",
            "",
            $"/// <summary>The permissions the {module} module declares.</summary>",
            $"public static class {name}Permissions",
            "{",
        };

        foreach (var permission in permissions.OrderBy(record => record.Id, StringComparer.Ordinal))
        {
            var key = permission.Id.StartsWith("permission/", StringComparison.Ordinal)
                ? permission.Id["permission/".Length..]
                : permission.Id;

            lines.AddRange(GenerateNaming.XmlDocLines(MeaningOf(permission), "    "));
            lines.Add($"    public const string {GenerateNaming.ConstName(key)} = \"{GenerateNaming.EscapeLiteral(permission.Id)}\";");
        }

        lines.Add("}");

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>
    ///     Renders every permission id as TypeScript: a const object of ids and their union type.
    /// </summary>
    /// <param name="permissions">Every permission record with its module.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderTypeScript(IReadOnlyList<(string Module, Record Permission)> permissions)
    {
        var ordered = permissions.OrderBy(entry => entry.Permission.Id, StringComparer.Ordinal).ToList();
        var lines = new List<string>
        {
            GenerateNaming.HeaderLine,
            "export const permissions = {",
        };

        foreach (var (module, permission) in ordered)
        {
            var key = permission.Id.StartsWith("permission/", StringComparison.Ordinal)
                ? permission.Id["permission/".Length..]
                : permission.Id;

            lines.Add($"  {GenerateNaming.ModulePascal(module)}{GenerateNaming.ConstName(key)}: \"{GenerateNaming.EscapeLiteral(permission.Id)}\",");
        }

        lines.Add("} as const;");
        lines.Add("export type PermissionId = (typeof permissions)[keyof typeof permissions];");

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>The permission's meaning, or its title when it states no meaning.</summary>
    /// <param name="permission">The permission record.</param>
    /// <returns>The meaning text.</returns>
    private static string MeaningOf(Record permission) =>
        permission.Field(LiteSpec.Model.RecordFields.Meaning) ?? permission.Title;
}
