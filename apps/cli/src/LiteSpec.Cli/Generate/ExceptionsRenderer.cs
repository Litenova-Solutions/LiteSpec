using System.Text;
using LiteSpec.Cli.Model.Refusals;
using LiteSpec.Model;

namespace LiteSpec.Cli.Generate;

/// <summary>
///     Renders one refusal exception per aggregate-declared refusal: a partial sealed
///     class deriving from the target base type, carrying the refusal code, the meaning
///     as its message, and the rule mark the marks table requires.
/// </summary>
/// <follows>litespec/core/model#generate-record-determined-code-from-the-records</follows>
static class ExceptionsRenderer
{
    /// <summary>One refusal exception the plan renders.</summary>
    /// <param name="Module">The record module name.</param>
    /// <param name="Aggregate">The aggregate record name, for the type prefix; empty when no aggregate record was found.</param>
    /// <param name="Entry">The declared refusal.</param>
    /// <param name="RuleId">The rule identifier the exception marks: the rule naming the refusal, or the rule the refusing step cites.</param>
    /// <param name="BaseType">The base type as the target declares it, qualified or simple.</param>
    /// <param name="Namespace">The C# namespace of the generated class.</param>
    /// <param name="Marks">The mark style the project declares.</param>
    public sealed record ExceptionData(
        string Module,
        string Aggregate,
        RefusalEntry Entry,
        string RuleId,
        string BaseType,
        string Namespace,
        MarkStyle Marks);

    /// <summary>
    ///     Renders one refusal as C#: an internal sealed partial class named for the
    ///     aggregate and the refusal, with a constructor passing the meaning and a Code
    ///     holding the refusal code. A refusal with parameters takes one string
    ///     constructor parameter per value and interpolates the message.
    /// </summary>
    /// <param name="data">The refusal exception the plan renders.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(ExceptionData data)
    {
        var type = TypeName(data.Module, data.Aggregate, data.Entry.Code);
        var lines = new List<string>
        {
            GenerateNaming.HeaderLineFor(GenerateNaming.CurrentVersion()),
            "// <auto-generated/>",
            "",
        };

        if (BaseUsing(data.BaseType, data.Namespace) is { } used)
        {
            lines.Add($"using {used};");
            lines.Add("");
        }

        lines.Add($"namespace {data.Namespace};");
        lines.Add("");
        lines.AddRange(DocLines(DocMeaningOf(data.Entry.Meaning, data.Entry.Parameters)));

        foreach (var parameter in data.Entry.Parameters)
        {
            lines.Add($"/// <param name=\"{parameter.Name}\">{GenerateNaming.EscapeXml(FlatOf(parameter.Meaning))}</param>");
        }

        lines.Add(data.Marks == MarkStyle.Attribute
            ? $"[Implements(\"{GenerateNaming.EscapeLiteral(data.RuleId)}\")]"
            : $"/// <implements>{GenerateNaming.EscapeXml(data.RuleId)}</implements>");

        lines.Add($"internal sealed partial class {type} : {BaseSimple(data.BaseType)}");
        lines.Add("{");
        lines.Add("    /// <summary>Creates the rejection.</summary>");

        var signature = string.Join(", ", data.Entry.Parameters.Select(parameter => $"string {parameter.Name}"));
        var message = data.Entry.Parameters.Count == 0
            ? $"\"{GenerateNaming.EscapeLiteral(data.Entry.Meaning)}\""
            : $"$\"{InterpolatedOf(data.Entry.Meaning)}\"";

        lines.Add($"    public {type}({signature})");
        lines.Add($"        : base({message})");
        lines.Add("    {");
        lines.Add("    }");
        lines.Add("");
        lines.Add("    /// <summary>The stable failure code.</summary>");
        lines.Add($"    public override string Code => \"{GenerateNaming.EscapeLiteral(data.Entry.Code)}\";");
        lines.Add("}");

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>The exception type name: the aggregate and refusal key in PascalCase with an Exception suffix.</summary>
    /// <param name="module">The record module name, for a refusal with no aggregate record.</param>
    /// <param name="aggregate">The aggregate record name, or empty when no aggregate record was found.</param>
    /// <param name="code">The refusal code.</param>
    /// <returns>The exception type name.</returns>
    public static string TypeName(string module, string aggregate, string code) =>
        (aggregate.Length > 0 ? GenerateNaming.ModulePascal(aggregate) : GenerateNaming.ModulePascal(module))
        + GenerateNaming.ConstName(KeyOf(code))
        + "Exception";

    /// <summary>The refusal key: the code's part after its module.</summary>
    /// <param name="code">The refusal code.</param>
    /// <returns>The key the constant and type names derive from.</returns>
    private static string KeyOf(string code) =>
        code.Contains('.', StringComparison.Ordinal)
            ? code[(code.IndexOf('.', StringComparison.Ordinal) + 1)..]
            : code;

    /// <summary>The simple base type name: the declared base type after its last dot.</summary>
    /// <param name="baseType">The base type as the target declares it.</param>
    /// <returns>The simple type name.</returns>
    private static string BaseSimple(string baseType) =>
        baseType.Contains('.', StringComparison.Ordinal)
            ? baseType[(baseType.LastIndexOf('.') + 1)..]
            : baseType;

    /// <summary>The namespace the file imports for its base type, or null when the base type is simple or already in scope.</summary>
    /// <param name="baseType">The base type as the target declares it.</param>
    /// <param name="namespace">The C# namespace of the generated class.</param>
    /// <returns>The imported namespace, or null when no import reads.</returns>
    private static string? BaseUsing(string baseType, string @namespace)
    {
        if (!baseType.Contains('.', StringComparison.Ordinal))
        {
            return null;
        }

        var used = baseType[..baseType.LastIndexOf('.')];

        return used == @namespace ? null : used;
    }

    /// <summary>The summary text of a meaning: each placeholder reads as a parameter reference, each escape as its brace, every other character escaped.</summary>
    /// <param name="meaning">The refusal meaning.</param>
    /// <param name="parameters">The values the meaning varies by.</param>
    /// <returns>The escaped documentation text with raw parameter references.</returns>
    private static string DocMeaningOf(string meaning, IReadOnlyList<RefusalParameter> parameters)
    {
        var names = parameters.Select(parameter => parameter.Name).ToHashSet(StringComparer.Ordinal);
        var built = new StringBuilder(meaning.Length);

        for (var at = 0; at < meaning.Length; at++)
        {
            if (meaning[at] == '{' && at + 1 < meaning.Length && meaning[at + 1] == '{')
            {
                built.Append('{');
                at++;
            }
            else if (meaning[at] == '}' && at + 1 < meaning.Length && meaning[at + 1] == '}')
            {
                built.Append('}');
                at++;
            }
            else if (meaning[at] == '{'
                && meaning.IndexOf('}', at + 1) is int end
                && end > at + 1
                && names.Contains(meaning[(at + 1)..end]))
            {
                built.Append("<paramref name=\"");
                built.Append(meaning[(at + 1)..end]);
                built.Append("\"/>");
                at = end;
            }
            else
            {
                built.Append(GenerateNaming.EscapeXml(meaning[at].ToString()));
            }
        }

        return built.ToString();
    }

    /// <summary>
    ///     The documentation lines of an escaped summary: one summary line, or one line per
    ///     summary line. The text is already escaped, so parameter references stay raw.
    /// </summary>
    /// <param name="doc">The escaped documentation text.</param>
    /// <returns>The documentation lines.</returns>
    private static List<string> DocLines(string doc)
    {
        var lines = doc.Replace("\r\n", "\n", StringComparison.Ordinal).Split('\n');

        if (lines.Length == 1)
        {
            return [$"/// <summary>{doc}</summary>"];
        }

        var built = new List<string> { $"/// <summary>{lines[0]}" };

        for (var index = 1; index < lines.Length; index++)
        {
            built.Add($"/// {lines[index]}");
        }

        built.Add("/// </summary>");

        return built;
    }

    /// <summary>The interpolated message body: each placeholder stays single, literal braces double, and literals escape.</summary>
    /// <param name="meaning">The refusal meaning.</param>
    /// <returns>The interpolated string body.</returns>
    private static string InterpolatedOf(string meaning)
    {
        var built = new StringBuilder(meaning.Length);

        for (var at = 0; at < meaning.Length; at++)
        {
            var character = meaning[at];

            if (character == '{' && at + 1 < meaning.Length && meaning[at + 1] == '{')
            {
                built.Append("{{");
                at++;
            }
            else if (character == '}' && at + 1 < meaning.Length && meaning[at + 1] == '}')
            {
                built.Append("}}");
                at++;
            }
            else if (character == '{'
                && meaning.IndexOf('}', at + 1) is int end
                && end > at + 1
                && IsIdentifier(meaning[(at + 1)..end]))
            {
                built.Append(meaning[at..(end + 1)]);
                at = end;
            }
            else if (character == '{' || character == '}')
            {
                built.Append(character);
                built.Append(character);
            }
            else
            {
                built.Append(GenerateNaming.EscapeLiteral(character.ToString()));
            }
        }

        return built.ToString();
    }

    /// <summary>Whether the name reads as an identifier: a letter or underscore opening letters, digits or underscores.</summary>
    /// <param name="name">The placeholder name.</param>
    /// <returns>True when the name reads as an identifier; otherwise false.</returns>
    private static bool IsIdentifier(string name)
    {
        if (name.Length == 0 || (name[0] != '_' && !char.IsLetter(name[0])))
        {
            return false;
        }

        for (var index = 1; index < name.Length; index++)
        {
            if (name[index] != '_' && !char.IsLetterOrDigit(name[index]))
            {
                return false;
            }
        }

        return true;
    }

    /// <summary>One line of documentation text: newlines read as spaces.</summary>
    /// <param name="text">The documentation text.</param>
    /// <returns>The flattened text.</returns>
    private static string FlatOf(string text) =>
        text.Replace("\r\n", " ", StringComparison.Ordinal).Replace('\n', ' ').Replace('\r', ' ');
}
