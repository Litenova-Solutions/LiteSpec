using LiteSpec.Cli.Model.Refusals;

namespace LiteSpec.Cli.Sync;

/// <summary>
///     Renders the refusal codes the records declare: per module a C# constant class, and
///     for a TypeScript client one file with the codes as a const array and their union type.
/// </summary>
/// <follows>litespec/core/model#sync-record-determined-code-from-the-records</follows>
static class RefusalCodesRenderer
{
    /// <summary>
    ///     Renders one module's refusal codes as C#: a public static class with one
    ///     public const string per refusal, named from the refusal key in PascalCase
    ///     and documented with the refusal's meaning.
    /// </summary>
    /// <param name="module">The record module name.</param>
    /// <param name="entries">The module's declared refusals.</param>
    /// <param name="namespace">The C# namespace of the synced class.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(string module, IReadOnlyList<RefusalEntry> entries, string @namespace)
    {
        var name = SyncNaming.ModulePascal(module);
        var lines = new List<string>
        {
            SyncNaming.HeaderLine,
            "// <auto-generated/>",
            "",
            $"namespace {@namespace};",
            "",
            $"/// <summary>The refusal codes the {module} module declares.</summary>",
            $"public static class {name}RefusalCodes",
            "{",
        };

        foreach (var entry in entries.OrderBy(entry => entry.Code, StringComparer.Ordinal))
        {
            var key = entry.Code.Contains('.', StringComparison.Ordinal)
                ? entry.Code[(entry.Code.IndexOf('.', StringComparison.Ordinal) + 1)..]
                : entry.Code;

            lines.AddRange(SyncNaming.XmlDocLines(entry.Meaning, "    "));
            lines.Add($"    public const string {SyncNaming.ConstName(key)} = \"{SyncNaming.EscapeLiteral(entry.Code)}\";");
        }

        lines.Add("}");

        return string.Join('\n', lines) + "\n";
    }

    /// <summary>
    ///     Renders every declared refusal code as TypeScript: a const array of codes
    ///     with their union type.
    /// </summary>
    /// <param name="entries">Every declared refusal.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderTypeScript(IReadOnlyList<RefusalEntry> entries)
    {
        var ordered = entries.OrderBy(entry => entry.Code, StringComparer.Ordinal).ToList();
        var lines = new List<string>
        {
            SyncNaming.HeaderLine,
            "export const refusals = [",
        };

        foreach (var entry in ordered)
        {
            lines.Add($"  \"{SyncNaming.EscapeLiteral(entry.Code)}\",");
        }

        lines.Add("] as const;");
        lines.Add("export type RefusalCode = (typeof refusals)[number];");

        return string.Join('\n', lines) + "\n";
    }
}
