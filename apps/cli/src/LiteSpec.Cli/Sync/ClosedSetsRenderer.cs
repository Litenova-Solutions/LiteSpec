namespace LiteSpec.Cli.Sync;

/// <summary>
///     Renders the closed value sets the records declare as C#: per home one static class
///     with a nested static class per set, each holding one const string per allowed value.
/// </summary>
/// <follows>litespec/core/model#sync-record-determined-code-from-the-records</follows>
static class ClosedSetsRenderer
{
    /// <summary>One closed value set a record declares: its record and its allowed values.</summary>
    /// <param name="RecordId">The identifier of the record declaring the set.</param>
    /// <param name="Name">The set name, the name segment of the record identifier.</param>
    /// <param name="Values">The allowed value texts.</param>
    public sealed record ClosedSet(string RecordId, string Name, IReadOnlyList<string> Values);

    /// <summary>
    ///     Renders one home's closed value sets as C#: a public static class with one nested
    ///     public static class per set, each holding one public const string per allowed value.
    /// </summary>
    /// <param name="home">The record home name: a module or a knowledge area.</param>
    /// <param name="sets">The home's closed value sets.</param>
    /// <param name="namespace">The C# namespace of the synced class.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(string home, IReadOnlyList<ClosedSet> sets, string @namespace)
    {
        var name = SyncNaming.ModulePascal(home);
        var lines = new List<string>
        {
            SyncNaming.HeaderLine,
            "// <auto-generated/>",
            "",
            $"namespace {@namespace};",
            "",
            $"/// <summary>The closed value sets of {home}.</summary>",
            $"public static class {name}ClosedSets",
            "{",
        };

        var takenClasses = new HashSet<string>(StringComparer.Ordinal);
        var first = true;

        foreach (var set in sets.OrderBy(candidate => candidate.RecordId, StringComparer.Ordinal))
        {
            if (!first)
            {
                lines.Add("");
            }

            first = false;
            var className = SyncNaming.UniqueName(SyncNaming.ConstName(set.Name), takenClasses);

            lines.Add($"    /// <summary>The closed value set {set.RecordId} declares.</summary>");
            lines.Add($"    public static class {className}");
            lines.Add("    {");

            var takenConsts = new HashSet<string>(StringComparer.Ordinal);

            foreach (var value in set.Values.OrderBy(text => text, StringComparer.Ordinal))
            {
                var constant = SyncNaming.UniqueName(SyncNaming.SanitizeConstName(value), takenConsts);

                lines.Add($"        /// <summary>The \"{SyncNaming.EscapeXml(value)}\" value.</summary>");
                lines.Add($"        public const string {constant} = \"{SyncNaming.EscapeLiteral(value)}\";");
            }

            lines.Add("    }");
        }

        lines.Add("}");

        return string.Join('\n', lines) + "\n";
    }
}
