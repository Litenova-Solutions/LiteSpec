using LiteSpec.Model;

namespace LiteSpec.Cli.Sync;

/// <summary>
///     Renders the domain event decisions the records state: per module a C# table with one
///     constant per event and a dictionary from each event identifier to its decision, so a
///     consumer's startup check compares against data instead of typed lists. Each decision
///     is the outcome the outbox decision check derives from the records, in the same words.
/// </summary>
/// <follows>litespec/core/model#sync-record-determined-code-from-the-records</follows>
static class EventDecisionsRenderer
{
    /// <summary>The decision the records state for a domain event: its outbox outcome with its record id.</summary>
    /// <param name="EventId">The domain event identifier.</param>
    /// <param name="Aggregate">The aggregate name the event identifier carries.</param>
    /// <param name="Name">The event name the event identifier carries.</param>
    /// <param name="Decision">The outcome the outbox decision check derives from the records.</param>
    public sealed record EventDecision(string EventId, string Aggregate, string Name, DomainEventOutcome Decision);

    /// <summary>
    ///     Renders one module's domain event decisions as C#: a public static class with one
    ///     public const string per event holding its decision, and a dictionary from each
    ///     event identifier to its decision.
    /// </summary>
    /// <param name="module">The record module name.</param>
    /// <param name="events">The module's domain events with the decision the records state for each.</param>
    /// <param name="namespace">The C# namespace of the synced class.</param>
    /// <returns>The file text with LF line endings.</returns>
    public static string RenderDotnet(string module, IReadOnlyList<EventDecision> events, string @namespace)
    {
        var name = SyncNaming.ModulePascal(module);
        var ordered = events.OrderBy(decided => decided.EventId, StringComparer.Ordinal).ToList();
        var lines = new List<string>
        {
            SyncNaming.HeaderLine,
            "// <auto-generated/>",
            "",
            $"namespace {@namespace};",
            "",
            $"/// <summary>The domain event decisions the records state for the {module} module.</summary>",
            $"public static class {name}EventDecisions",
            "{",
        };

        foreach (var decided in ordered)
        {
            var constant = SyncNaming.ModulePascal(decided.Aggregate) + SyncNaming.ConstName(decided.Name);
            var value = DomainEventOutcomes.Value(decided.Decision);

            lines.Add($"    /// <summary>The decision the records state for {decided.EventId}: {value}.</summary>");
            lines.Add($"    public const string {constant} = \"{value}\";");
        }

        lines.Add("");
        lines.Add("    /// <summary>Every domain event the records declare with the decision the records state for it, by event identifier.</summary>");
        lines.Add("    public static readonly System.Collections.Generic.IReadOnlyDictionary<string, string> Decisions = new System.Collections.Generic.Dictionary<string, string>(System.StringComparer.Ordinal)");
        lines.Add("    {");

        foreach (var decided in ordered)
        {
            var constant = SyncNaming.ModulePascal(decided.Aggregate) + SyncNaming.ConstName(decided.Name);

            lines.Add($"        [\"{SyncNaming.EscapeLiteral(decided.EventId)}\"] = {constant},");
        }

        lines.Add("    };");
        lines.Add("}");

        return string.Join('\n', lines) + "\n";
    }
}
