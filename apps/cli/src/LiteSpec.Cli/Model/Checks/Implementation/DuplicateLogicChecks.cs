using System.Text;
using LiteSpec.Cli.Files;
using LiteSpec.Cli.Model.Configuration;
using LiteSpec.Cli.Model.Readers.Dotnet;
using LiteSpec.Model;
using LiteSpec.Model.Roslyn;
using LiteSpec.Standards;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;

namespace LiteSpec.Cli.Model.Checks.Implementation;

/// <summary>The duplicate-logic check: one rule, calculation or projection keeps one home instead of living as a copy in two slices.</summary>
/// <follows>litespec/core/domain-model#keep-one-home-for-each-rule-calculation-and-projection</follows>
/// <follows>litespec/backend/dotnet/application#call-shared-logic-instead-of-copying-it</follows>
internal static class DuplicateLogicChecks
{
    /// <summary>
    ///     The smallest body the check compares, in statements: six statements is the smallest body
    ///     that carries a rule, calculation or projection worth its own home. Shorter bodies repeat by
    ///     design, a guard, a mapping, or one domain call, and comparing them would report every
    ///     handler shaped alike.
    /// </summary>
    internal const int MinStatements = 6;

    /// <summary>
    ///     The smallest body the check compares, in tokens: eighty tokens catches the same size
    ///     expressed as one long statement, such as a single projection or a long boolean test.
    ///     Below that, shared call shapes repeat by design.
    /// </summary>
    internal const int MinTokens = 80;

    /// <summary>
    ///     Reports each method or local-function body of at least the threshold size whose normalized
    ///     text repeats in two or more different folders: the same logic lives in two slices, so one
    ///     rule keeps two homes. Same-file and same-folder repeats are not reported. Generated code
    ///     and test projects are left out.
    /// </summary>
    /// <param name="model">The loaded project model that holds the consumer configuration.</param>
    /// <param name="findings">The list that receives each finding this check raises.</param>
    internal static void Run(ProjectModel model, List<Finding> findings)
    {
        if (!model.Config.Layers.Covers("logic-duplicate", model.Config.Extensions))
        {
            return;
        }

        var bodies = ReadBodies(model.Config);

        foreach (var group in bodies.GroupBy(entry => entry.Hash, StringComparer.Ordinal).OrderBy(group => group.Key, StringComparer.Ordinal))
        {
            var places = group.OrderBy(entry => entry.File, StringComparer.Ordinal).ThenBy(entry => entry.Line).ToList();

            if (places.Select(entry => entry.Folder).Distinct(StringComparer.Ordinal).Count() < 2)
            {
                continue;
            }

            var first = places[0];
            var listed = string.Join(", ", places.Select(entry => PlaceOf(model.Config.Root, entry)));

            findings.Add(new Finding(
                "logic-duplicate",
                $"The same method body appears in {places.Count} folders ({listed}); move the logic to its one home (the aggregate, a domain service, or the knowledge model) and call it from each slice.",
                first.File,
                first.Line,
                null));
        }
    }

    /// <summary>One compared body: its hash with the file, folder and line where it sits.</summary>
    /// <param name="Hash">The sixteen-hex-character hash of the normalized body text.</param>
    /// <param name="Name">The simple name of the method or local function.</param>
    /// <param name="Type">The simple name of the containing type, or empty when declared outside a type.</param>
    /// <param name="File">The file holding the body.</param>
    /// <param name="Folder">The folder holding the file.</param>
    /// <param name="Line">The 1-based line of the declaration name.</param>
    sealed record ComparedBody(string Hash, string Name, string Type, string File, string Folder, int Line);

    /// <summary>Every compared body of the backend: each method and local-function body of at least the threshold size that is not generated and sits outside the test projects.</summary>
    /// <param name="config">The consumer configuration naming the source roots.</param>
    /// <returns>Each compared body in file order.</returns>
    private static List<ComparedBody> ReadBodies(ConsumerConfig config)
    {
        var bodies = new List<ComparedBody>();

        foreach (var file in BackendFiles(config))
        {
            string text;

            try
            {
                text = File.ReadAllText(file);
            }
            catch (Exception exception) when (exception is IOException or UnauthorizedAccessException)
            {
                continue;
            }

            if (HasAutoGeneratedMarker(text))
            {
                continue;
            }

            var tree = CSharpSyntaxTree.ParseText(text, new CSharpParseOptions(LanguageVersion.Preview), file);

            if (tree.GetDiagnostics().Any(diagnostic => diagnostic.Severity == DiagnosticSeverity.Error))
            {
                continue;
            }

            var folder = Path.GetDirectoryName(file) ?? file;

            foreach (var body in MethodBodies.Read(tree))
            {
                if (body.Statements < MinStatements && body.Tokens < MinTokens)
                {
                    continue;
                }

                bodies.Add(new ComparedBody(HashOf(body.Normalized), body.Name, body.Type, file, folder, body.Line));
            }
        }

        return bodies;
    }

    /// <summary>Every backend C# file the check compares, outside the test projects and generated file names, in ordinal path order.</summary>
    /// <param name="config">The consumer configuration naming the source roots.</param>
    /// <returns>Each compared file in ordinal path order.</returns>
    private static List<string> BackendFiles(ConsumerConfig config)
    {
        var files = new List<string>();

        foreach (var root in SourceRoots.BackendRoots(config))
        {
            foreach (var file in SourceTree.Files(root, ".cs"))
            {
                if (GeneratedCode.IsGeneratedFileName(file) || UnderTestRoots(config, file))
                {
                    continue;
                }

                files.Add(file);
            }
        }

        files.Sort(StringComparer.Ordinal);

        return files;
    }

    /// <summary>Whether the file sits under a configured test root.</summary>
    /// <param name="config">The consumer configuration naming the test roots.</param>
    /// <param name="file">The file path.</param>
    /// <returns>True when the file sits under a test root.</returns>
    private static bool UnderTestRoots(ConsumerConfig config, string file) =>
        config.TestRoots.Any(root => SourceRoots.IsUnder(root, file));

    /// <summary>Whether an auto-generated marker sits on one of the first two lines, as the shared generated-code reader judges.</summary>
    /// <param name="text">The file text.</param>
    /// <returns>True when one of the first two lines carries the marker.</returns>
    private static bool HasAutoGeneratedMarker(string text)
    {
        var start = 0;

        for (var line = 0; line < 2; line++)
        {
            var end = text.IndexOf('\n', start);
            var current = end < 0 ? text.Substring(start) : text.Substring(start, end - start);

            if (current.Contains("<auto-generated", StringComparison.Ordinal))
            {
                return true;
            }

            if (end < 0)
            {
                return false;
            }

            start = end + 1;
        }

        return false;
    }

    /// <summary>The hash of a normalized body: its sixteen-hex-character SHA-256, as the test-method hash reads.</summary>
    /// <param name="normalized">The normalized body text.</param>
    /// <returns>The sixteen-hex-character hash.</returns>
    private static string HashOf(string normalized) =>
        Convert.ToHexString(Sha256.Hash(Encoding.UTF8.GetBytes(normalized)))[..16].ToLowerInvariant();

    /// <summary>One place as the finding lists it: the method with its root-relative file and line.</summary>
    /// <param name="root">The consumer root the file is relative to.</param>
    /// <param name="body">The compared body.</param>
    /// <returns>The place text.</returns>
    private static string PlaceOf(string root, ComparedBody body)
    {
        var method = body.Type.Length > 0 ? body.Type + "." + body.Name : body.Name;

        return "'" + method + "' at '" + PathText.Relative(root, body.File) + ":" + body.Line + "'";
    }
}
