namespace LiteSpec.Model;

/// <summary>
///     The generated record union each web frontend imports: the use-case ids its
///     modules may mark, so a mistyped mark fails the type check.
/// </summary>
static class FrontendRecords
{
    /// <summary>How long a single-line union may run before each id takes its own line.</summary>
    private const int MaxSingleLineLength = 120;

    /// <summary>
    ///     Writes <c>src/lib/litespec-records.ts</c> for every React and Svelte frontend,
    ///     returning the written paths relative to the root.
    /// </summary>
    public static IReadOnlyList<string> Write(ProjectModel model)
    {
        var written = new List<string>();
        var ids = UseCaseIds(model);

        foreach (var frontend in model.Config.Frontends)
        {
            if (frontend.Platform is not ("svelte" or "react"))
            {
                continue;
            }

            var path = Path.Combine(frontend.Path, "src", "lib", "litespec-records.ts");
            Directory.CreateDirectory(Path.GetDirectoryName(path)!);
            File.WriteAllText(path, Render(ids));
            written.Add(model.Config.Relative(path));
        }

        return written;
    }

    /// <summary>
    ///     Every use case reached through a browser entry point, sorted. The project
    ///     maps no entry point to one frontend, so every web frontend serves them all.
    /// </summary>
    public static IReadOnlyList<string> UseCaseIds(ProjectModel model) =>
        [
            .. model.Records
                .Where(record => record.Type == "use-case" && ReachedThroughBrowser(model, record))
                .Select(record => record.Id)
                .OrderBy(id => id, StringComparer.Ordinal),
        ];

    /// <summary>Renders the union file: a header, the id union, and the mark interface.</summary>
    public static string Render(IReadOnlyList<string> ids)
    {
        var lines = new List<string>
        {
            "// This file is generated by litespec model build. Do not edit it by hand.",
        };

        if (ids.Count == 0)
        {
            lines.Add("export type UseCaseId = never;");
        }
        else
        {
            var single = $"export type UseCaseId = {string.Join(" | ", ids.Select(id => $"\"{id}\""))};";

            if (single.Length <= MaxSingleLineLength)
            {
                lines.Add(single);
            }
            else
            {
                lines.Add("export type UseCaseId =");

                for (var index = 0; index < ids.Count; index++)
                {
                    lines.Add(index + 1 < ids.Count ? $"  | \"{ids[index]}\"" : $"  | \"{ids[index]}\";");
                }
            }
        }

        lines.Add("export interface LiteSpecMark { readonly implements: UseCaseId }");

        return string.Join('\n', lines) + "\n";
    }

    private static bool ReachedThroughBrowser(ProjectModel model, Record record) =>
        record.Ids("reachedThrough").Any(id =>
            model.ById.TryGetValue(id, out var point)
            && point.Type == "entry-point"
            && point.Field("kind") == "browser");
}
