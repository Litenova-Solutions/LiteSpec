    /// <summary>The codes by name.</summary>
    private static readonly Dictionary<string, FindingCode> ByCode = All.ToDictionary(code => code.Code, StringComparer.Ordinal);

    /// <summary>Gets the codes the model needs in order to load. No waiver covers them, and a waiver that names one is itself invalid.</summary>
    public static IReadOnlyCollection<string> Load { get; } =
    [
        "record-invalid", "record-placement-invalid",
        "identifier-invalid", "identifier-duplicate", "reference-unknown",
    ];

    /// <summary>Whether a code is one the tools emit.</summary>
    /// <param name="code">The finding code.</param>
    /// <returns>True when the table holds the code.</returns>
    public static bool IsKnown(string code) => ByCode.ContainsKey(code);

    /// <summary>The table row of a code.</summary>
    /// <param name="code">The finding code.</param>
    /// <returns>The row; a code the table does not hold throws, because every emitted code is in the table.</returns>
    public static FindingCode Of(string code) =>
        ByCode.TryGetValue(code, out var row) ? row : throw new KeyNotFoundException($"Finding code '{code}' is not in FindingCodes.");
